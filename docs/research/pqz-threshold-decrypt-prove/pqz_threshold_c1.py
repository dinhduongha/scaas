# Research harness C1, UNAUDITED. Not production code; kept with docs/research/pqz-threshold-decrypt-prove.md (§12).
# PQZ only (classical Zether is a separate system and is not touched here).
#
# PQZ threshold decryption by MPC rounding, simulated in one process:
#   - a dealer Shamir-shares the PQZ secret s over F_q (degree d = (n - 1) / 2, honest majority, all n online);
#   - each party computes its partial u^T s_j locally (linear) and so a share of y = v - u^T s + floor(Delta / 2) + Delta B;
#   - the parties compute M = floor(y / Delta) - B inside MPC (B = floor(q / 2 Delta): pqz_dec centres, digit sums may be < 0) (mask-then-open with a mixed-radix random r = r_hi Delta + r_lo
#     made from shared random bits; bitwise comparisons by a log-depth prefix-OR; Shamir multiplication by resharing,
#     Gennaro-Rabin-Rabin / BGW degree reduction); only c = y + r mod q (uniform) and M are ever opened;
#   - M is checked equal to the real decryption: the M fields of the frozen vectors (written by the C core's Dec through
#     pqz-vectors) at all four sets, including the reachable worst case (4,095 credits at B_FRESH, worstcase_noise.json).
# Negative controls that must fail: a wrong key share (caught by the opening's degree check; slips through a fast path
# that opens from d + 1 shares only), too few parties (d < t), a caller-supplied ciphertext (refused by the state rule;
# without it the rounding oracle recovers s in 8 K queries), and a comparator mutant.
#
# What is simulated, precisely: every party is a list slot in one process; "sending" is a counter, no network, no
# authentication, no malicious-security checks on multiplications (semi-honest GRR; openings are checked for degree-d
# consistency only). Random shared bits are generated by the standard square-root method from a jointly random value
# (every party contributes a random sharing); nothing secret is computed in the clear, but the dealer of the key shares is
# trusted (C2 in the roadmap). No timing is measured; the cost model counts rounds, multiplications and field elements.
#
# Run (repo root): python3 docs/research/pqz-threshold-decrypt-prove/pqz_threshold_c1.py   (four sets: n = 5; default set: 3, 5, 7)
#                  python3 docs/research/pqz-threshold-decrypt-prove/pqz_threshold_c1.py --set n2304-kmax4096 --n 3,5
