class Abort(Exception):
    pass


class Net:
    """n parties, Shamir degree d over F_q; every shared value is a list of n shares (party j holds point j + 1)."""

    def __init__(s, n, q, online=None):
        s.n, s.q, s.d = n, q, (n - 1) // 2
        s.online = online or n
        s.rounds = s.mults = s.opens = s.sent = 0   # sent: field elements sent per party (sum over rounds)
        s.log = []                                  # what was opened, by label (never w, noise or a key share)
        s.lam = s.lagr(list(range(1, n + 1)), 0)

    def lagr(s, pts, at):
        out = []
        for i in pts:
            num = den = 1
            for j in pts:
                if j != i: num = num * (at - j) % s.q; den = den * (i - j) % s.q
            out.append(num * pow(den, -1, s.q) % s.q)
        return out

    def share(s, x):
        cs = [x % s.q] + [secrets.randbelow(s.q) for _ in range(s.d)]
        return [sum(c * pow(j, k, s.q) for k, c in enumerate(cs)) % s.q for j in range(1, s.n + 1)]

    def const(s, x): return [x % s.q] * s.n
    def add(s, a, b): return [(x + y) % s.q for x, y in zip(a, b)]
    def sub(s, a, b): return [(x - y) % s.q for x, y in zip(a, b)]
    def cmul(s, k, a): return [k * x % s.q for x in a]
    def lin(s, terms, c=0):  # c + sum k * a
        out = s.const(c)
        for k, a in terms: out = s.add(out, s.cmul(k, a))
        return out

    def rand(s, cnt):  # every party deals a random sharing; the sum is random if one party is honest
        s.rounds += 1; s.sent += cnt * (s.n - 1)
        out = []
        for _ in range(cnt):
            acc = s.const(0)
            for _ in range(s.n): acc = s.add(acc, s.share(secrets.randbelow(s.q)))
            out.append(acc)
        return out

    def mul(s, pairs):  # one round, a batch of products: local degree-2d product, reshare, recombine (needs 2d + 1)
        if s.online < 2 * s.d + 1:
            raise Abort(f'multiplication needs 2d + 1 = {2 * s.d + 1} online parties, {s.online} online')
        s.rounds += 1; s.mults += len(pairs); s.sent += len(pairs) * (s.n - 1)
        out = []
        for a, b in pairs:
            sub = [s.share(x * y % s.q) for x, y in zip(a, b)]
            out.append([sum(s.lam[j] * sub[j][k] for j in range(s.n)) % s.q for k in range(s.n)])
        return out

    def open(s, vals, label, check=True, pts=None):
        """open a batch; with check, all n shares must lie on one degree-d polynomial (detects up to n - d - 1 bad
        shares); without, the first d + 1 points (or pts) are interpolated as they come."""
        s.rounds += 1; s.opens += len(vals); s.sent += len(vals) * (s.n - 1)
        pts = pts or list(range(1, s.d + 2))
        lam0 = s.lagr(pts, 0)
        out = []
        for a in vals:
            x = sum(l * a[p - 1] for l, p in zip(lam0, pts)) % s.q
            if check:
                for m in range(1, s.n + 1):
                    if m not in pts and sum(l * a[p - 1] for l, p in zip(s.lagr(pts, m), pts)) % s.q != a[m - 1]:
                        raise Abort(f'{label}: shares do not lie on one degree-{s.d} polynomial')
            out.append(x)
        s.log.append((label, len(vals)))
        return out


def sqrt_mod(a, q):  # Tonelli-Shanks (q = 9 mod 16 at every set, so q = 1 mod 8: no shortcut)
    if a == 0: return 0
    assert pow(a, (q - 1) // 2, q) == 1
    Qs, S = q - 1, 0
    while Qs % 2 == 0: Qs //= 2; S += 1
    z = 2
    while pow(z, (q - 1) // 2, q) != q - 1: z += 1
    M, c, t, R = S, pow(z, Qs, q), pow(a, Qs, q), pow(a, (Qs + 1) // 2, q)
    while t != 1:
        i, tt = 0, t
        while tt != 1: tt = tt * tt % q; i += 1
        b = pow(c, 1 << (M - i - 1), q); M, c, t, R = i, b * b % q, t * b * b % q, R * b % q
    return R


def rand_bits(net, cnt):
    """cnt shared uniform bits: [a] random, open a^2, b = (a / sqrt(a^2) + 1) / 2 with the canonical root."""
    q, inv2, out = net.q, pow(2, -1, net.q), []
    while len(out) < cnt:
        need = cnt - len(out)
        a = net.rand(need)
        a2 = net.open(net.mul([(x, x) for x in a]), 'a^2 (random, for bits)')
        for x, v in zip(a, a2):
            if v == 0: continue
            rt = sqrt_mod(v, q); rt = min(rt, q - rt)
            out.append(net.lin([(pow(rt, -1, q) * inv2, x)], inv2))
    return out


def lt_batch(net, items):
    """items: (public a, shared bits of x, LSB first). Returns [(a < x, a == x)] as shares, all items in the same
    rounds: d_i = a_i XOR x_i (linear), prefix-OR from the top in ceil(log2 L) rounds, e_i = f_i - f_{i+1},
    [a < x] = sum e_i (1 - a_i), [a == x] = 1 - f_0."""
    L = max(len(xb) for _, xb in items)
    f = []
    for a, xb in items:
        xb = xb + [net.const(0)] * (L - len(xb))
        assert 0 <= a < 2**L
        f.append([net.lin([(-1, x)], 1) if (a >> i) & 1 else x for i, x in enumerate(xb)])
    st = 1
    while st < L:
        pairs = [(fi[i], fi[i + st]) for fi in f for i in range(L - st)]
        prods = iter(net.mul(pairs))
        for fi in f:
            new = list(fi)
            for i in range(L - st):
                new[i] = net.sub(net.add(fi[i], fi[i + st]), next(prods))
            fi[:] = new
        st *= 2
    out = []
    for (a, _), fi in zip(items, f):
        lt = net.const(0)
        for i in range(L):
            if not (a >> i) & 1:
                lt = net.add(lt, net.sub(fi[i], fi[i + 1] if i + 1 < L else net.const(0)))
        out.append((lt, net.lin([(-1, fi[0])], 1)))
    return out


class Rounder:
    """The MPC rounding floor(y / Delta) for any y in [0, q) (the caller shifts y so that the proven range sits inside)."""

    def __init__(s, net, q, delta):
        s.net, s.q, s.D = net, q, delta
        s.Lh, s.Ll = (q // delta).bit_length(), (delta - 1).bit_length()
        s.qh, s.ql = divmod(q - 1, delta)

    def mask(s, cnt):
        """offline: cnt random r = r_hi Delta + r_lo, uniform in [0, q), with the bits of r_hi and r_lo.
        r_lo < Delta and r < q are tested in MPC and only the accept bit opens (independent of any input)."""
        net, out = s.net, []
        while len(out) < cnt:
            need = 2 * (cnt - len(out)) + 4                           # over-draw: r < q accepts about half
            flat = rand_bits(net, need * s.Ll)                       # all bits of a batch in the same rounds
            lo = [flat[k * s.Ll:(k + 1) * s.Ll] for k in range(need)]
            ok = net.open([net.lin([(-1, lt)], 1) for lt, _ in lt_batch(net, [(s.D - 1, b) for b in lo])],
                          'accept bit r_lo < Delta')
            lo = [b for b, k in zip(lo, ok) if k == 1]
            if not lo: continue
            flat = rand_bits(net, len(lo) * s.Lh)
            hi = [flat[k * s.Lh:(k + 1) * s.Lh] for k in range(len(lo))]
            cmp_hi = lt_batch(net, [(s.qh, b) for b in hi])
            cmp_lo = lt_batch(net, [(s.ql, b) for b in lo])
            ands = net.mul([(eq, lt) for (_, eq), (lt, _) in zip(cmp_hi, cmp_lo)])
            gt = [net.add(lt, a) for (lt, _), a in zip(cmp_hi, ands)]          # [q - 1 < r]
            ok = net.open([net.lin([(-1, g)], 1) for g in gt], 'accept bit r < q')
            for bh, bl, k in zip(hi, lo, ok):
                if k == 1 and len(out) < cnt:
                    r_hi = net.lin([(1 << i, b) for i, b in enumerate(bh)])
                    r_lo = net.lin([(1 << i, b) for i, b in enumerate(bl)])
                    out.append((net.lin([(s.D, r_hi), (1, r_lo)]), r_hi, bh, bl))
        return out

    def round(s, ys, masks, out_check=True, open_pts=None):
        """online: open c = y + r, then M = c_hi - r_hi - [c_lo < r_lo] + wrap (c'_hi - c_hi - [c'_lo < r_lo] +
        [c_lo < r_lo]), wrap = [c < r] (mixed radix), c' = c + q."""
        net, D = s.net, s.D
        cs = net.open([net.add(y, r) for y, (r, _, _, _) in zip(ys, masks)], 'c = y + r mod q (uniform mask)',
                      check=out_check, pts=open_pts)
        items = []
        for c, (_, _, bh, bl) in zip(cs, masks):
            (ch, cl), (_, cl2) = divmod(c, D), divmod(c + s.q, D)
            items += [(ch, bh), (cl, bl), (cl2, bl)]
        res = lt_batch(net, items)
        trip = [res[3 * k:3 * k + 3] for k in range(len(cs))]
        ands = net.mul([(t[0][1], t[1][0]) for t in trip])                   # [c_hi == r_hi] * [c_lo < r_lo]
        wraps = [net.add(t[0][0], a) for t, a in zip(trip, ands)]            # [c < r]
        diffs = []
        for c, t in zip(cs, trip):
            ch, c2h = c // D, (c + s.q) // D
            diffs.append(net.lin([(-1, t[2][0]), (1, t[1][0])], c2h - ch))
        prods = net.mul(list(zip(wraps, diffs)))
        return [net.lin([(-1, rh), (-1, t[1][0]), (1, p)], c // D)
                for c, (_, rh, _, _), t, p in zip(cs, masks, trip, prods)]


def signed(q, xs):  # an opened M is a field element; pqz_dec's M is centred (Sub gives negative digit sums)
    return [x - q if x > q // 2 else x for x in xs]


def negacyclic_dot(us, ss, q, want):
    """coefficients `want` of sum_j us[j] * ss[j] in Z_q[X]/(X^64 + 1), general coefficients (Kronecker, 128-bit slots)."""
    W, out = 128, [0] * 128
    acc = 0
    for a, b in zip(us, ss):
        pa = int.from_bytes(b''.join(c.to_bytes(16, 'little') for c in a), 'little')
        pb = int.from_bytes(b''.join(c.to_bytes(16, 'little') for c in b), 'little')
        acc += pa * pb
    raw = acc.to_bytes(16 * 130, 'little')
    full = [int.from_bytes(raw[16 * i:16 * i + 16], 'little') for i in range(128)]
    return [(full[k] - full[k + 64]) % q for k in want]


def main_set(setname, ns):
    os.environ['PQZ_SET'] = setname
    sys.path.insert(0, os.path.join(ROOT, 'smartcontracts/vectors/pqz'))
    import pqz_kat as P
    q, D, K, N = P.Q, P.DELTA, P.K, P.N
    # floor((w + floor(D/2)) / D) == floor((2w + D) / (2D)) for odd and even D (n2304-kmax4096: D even); pqz_dec centres
    # w, and Sub gives negative digit sums, so the window is shifted by D * B: M in [-B, q / D - B), B = floor(q / 2D)
    B = q // (2 * D)
    h = D // 2 + D * B
    assert P.Q // D >= 2**P.M_BITS
    vd = P.VEC_DIR
    print(f'== set {setname}: q = {q} (2^{q.bit_length() - 1}+), Delta = {D}, K = {K}, MBITS = {P.M_BITS}')

    # ---- the cases: frozen vectors (C core Dec wrote every expected M) and the state the service may decrypt
    enc = json.load(open(os.path.join(vd, 'enc.json')))
    cases, state = [], {}
    cts = []
    for i, row in enumerate(enc['rows']):
        u, vs, _ = P.enc_of(row)
        for k, (leg, v) in enumerate(zip(row['legs'], vs)):
            cases.append((f'enc row {i} leg {k} (fresh, value {leg["value"]})', P.key(row['recipients'][k])[1], u + v, 0, leg['M']))
        cts.append(u + vs[0])
    for o in enc['ops']:
        b = {'trivial 1000': P.trivial(P.digits(1000)), 'row 5 leg 0': cts[5]}[o['b']]
        c = P.ct_add(cts[0], b) if o['op'] == 'add' else P.ct_sub(cts[0], b)
        cases.append((f'enc op {o["op"]} {o["b"]}', P.key(o['dec_key'])[1], c, 0, o['M']))
    wc = json.load(open(os.path.join(vd, 'worstcase_noise.json')))['bound']
    s_w = P.from_sparse(wc['receiver']['s']); e_w = P.from_sparse(wc['receiver']['e'])
    t_ = P.mul_A(P.polys(s_w))
    pk_w = P.enc_vec([[(t_[i][k] + e_w[P.D * i + k]) % q for k in range(P.D)] for i in range(K)])
    cr = wc['credit']
    u, vs = P.encrypt([pk_w], [P.digits(cr['value'])], P.from_sparse(cr['r']), P.from_sparse(cr['e1']), [cr['e2']])
    ct1 = u + vs[0]; nc = P.K_MAX - 1
    T = P.ct_add(b''.join(x.to_bytes(8, 'big') for x in [(nc * c) % q for c in P.dec_coeffs(ct1)]), P.trivial(P.digits(wc['plain_used'])))
    cases.append((f'worst case T: {nc:,} credits at B_FRESH, noise {wc["max_abs_noise"]:,}', s_w, T, 0, wc['T_M']))
    # not frozen: a v at window 3 (the auditor copy of an R_TXM leg); expected M from the reference Dec
    seed = enc['rows'][0]['recipients'][0]; pk3, s3 = P.key(seed)[0], P.key(seed)[1]
    u3, v3 = P.encrypt([pk3], [P.digits(0xFEDCBA9876543210)], *P.enc_sample(b'\x77' * 32, 1)[:3], win=[3])
    cases.append(('window 3 copy (not a frozen vector; expected from the reference Dec)', s3, u3 + v3[0], 3,
                  P.dec(s3, u3 + v3[0], 3)[0]))
    for name, s, ct, win, M in cases:
        assert P.dec(s, ct, win)[0] == M, f'reference Dec disagrees with the vector: {name}'   # the comparator itself
        state[hashlib.sha256(ct).digest()] = (s, ct, win)

    def partials(net, shares, ct, win):  # local: party j's share of y = v - u^T s + h at the 16 coefficients
        us = P.polys(P.dec_coeffs(ct[:P.PK_BYTES])); v = P.dec_coeffs(ct[P.PK_BYTES:])
        want = [16 * win + i for i in range(16)]
        per = [negacyclic_dot(us, P.polys(sj), q, want) for sj in shares]
        return [[(v[i] - per[j][i] + h) % q for j in range(net.n)] for i in range(16)]

    def decrypt(net, rnd, shares, ct, win, **kw):
        ys = partials(net, shares, ct, win)
        return [net.lin([(1, m)], -B) for m in rnd.round(ys, rnd.mask(16), **kw)]

    def deal(net, s):  # the trusted dealer (roadmap C2): Shamir shares of every coefficient of s
        cols = [net.share(c) for c in s]
        return [[cols[k][j] for k in range(N)] for j in range(net.n)]

    for n in ns:
        net = Net(n, q); rnd = Rounder(net, q, D)
        print(f'-- n = {n}, degree d = {net.d}, reconstruct t = {net.d + 1}, multiplications need {2 * net.d + 1} online')
        for name, s, ct, win, M in cases:
            net.rounds = net.mults = net.opens = net.sent = 0; net.log = []
            got = signed(q, net.open(decrypt(net, rnd, deal(net, s), ct, win), 'M (output)'))
            ok = got == M
            print(f'   {"ok  " if ok else "FAIL"} {name}: MPC M == frozen M: {ok}')
            assert ok
        # cost of one decryption (the first case), offline (masks) and online counted apart
        net2 = Net(n, q); rnd2 = Rounder(net2, q, D); sh = deal(net2, cases[0][1])
        masks = rnd2.mask(16); off = (net2.rounds, net2.mults, net2.opens, net2.sent)
        net2.rounds = net2.mults = net2.opens = net2.sent = 0; net2.log = []
        Mx = signed(q, net2.open([net2.lin([(1, m)], -B) for m in rnd2.round(partials(net2, sh, cases[0][2], 0), masks)], 'M (output)'))
        assert Mx == cases[0][4]
        on = (net2.rounds, net2.mults, net2.opens, net2.sent)
        opened = sorted({lab for lab, _ in net2.log})
        print(f'   cost per decryption (16 coefficients): offline {off[0]} rounds, {off[1]} multiplications, '
              f'{off[2]} openings, {off[3]} field elements sent per party; online {on[0]} rounds, {on[1]} '
              f'multiplications, {on[2]} openings, {on[3]} field elements sent per party (8 B each)')
        print(f'   online openings: {opened}')
        assert opened == ['M (output)', 'c = y + r mod q (uniform mask)']
    # ---- negative controls (n = 5, the default-sized case: the first fresh credit)
    name, s, ct, win, M = cases[0]
    net = Net(5, q); rnd = Rounder(net, q, D)
    sh = deal(net, s); bad = [list(x) for x in sh]; bad[1][7] = (bad[1][7] + 12345) % q   # party 2: one wrong coefficient
    try:
        decrypt(net, rnd, bad, ct, win); r1 = 'not caught'
    except Abort as x:
        r1 = f'Abort ({x})'
    print(f'   N1 wrong key share of party 2, all 5 shares checked at the opening: {r1}'); assert r1.startswith('Abort')
    got = signed(q, net.open(decrypt(net, rnd, bad, ct, win, out_check=False, open_pts=[1, 2, 3]), 'M', check=False, pts=[1, 2, 3]))
    print(f'   N1b the same share, fast path opening from parties 1-3 only: M == frozen: {got == M}'); assert got != M
    net3 = Net(5, q, online=2); rnd3 = Rounder(net3, q, D)
    try:
        decrypt(net3, rnd3, sh, ct, win); r2 = 'ran'
    except Abort as x:
        r2 = f'Abort ({x})'
    print(f'   N2a only d = 2 parties online: {r2}'); assert r2.startswith('Abort')
    us = P.polys(P.dec_coeffs(ct[:P.PK_BYTES])); v = P.dec_coeffs(ct[P.PK_BYTES:])
    lam = net.lagr([1, 2], 0)
    uts = [sum(l * x for l, x in zip(lam, xs)) % q for xs in zip(*[negacyclic_dot(us, P.polys(sh[j]), q, range(16)) for j in (0, 1)])]
    M2 = [((P.centre(v[i] - uts[i]) * 2 + D) // (2 * D)) for i in range(16)]
    print(f'   N2b two partials (d < t) interpolated and rounded in the clear: M == frozen: {M2 == M}'); assert M2 != M

    def service(ct):  # the C1 service: decrypts only ciphertexts it finds in (simulated) chain state
        if hashlib.sha256(ct).digest() not in state:
            raise Abort('NotChainState: the service decrypts only ciphertexts it reads from chain state')
        return state[hashlib.sha256(ct).digest()]
    assert service(ct)[1] == ct                                      # positive control: a state ciphertext is served
    try:
        forged = bytes(P.PK_BYTES - 8) + (1).to_bytes(8, 'big') + bytes(P.V_BYTES); service(forged); r3 = 'served'
    except Abort as x:
        r3 = f'Abort ({x})'
    print(f'   N3 caller-supplied ciphertext: {r3}'); assert r3.startswith('Abort')
    # why: without the rule the rounding is an oracle. u = the unit polynomial at poly j, v_i = ceil(Delta / 2) + off:
    # M_i = 1 iff s_j[16 w + i] <= off; two queries per window give s in {-1, 0, 1}; 4 windows x K polys x 2 = 8 K.
    def oracle(ctb, w):  # the ideal functionality the MPC computes (shown equal above); 2 queries also through the MPC
        return P.dec(s, ctb, w)[0]
    rec, queries, through = [0] * N, 0, 0
    for j in range(K):
        u_ = [[0] * 64 for _ in range(K)]; u_[j][0] = 1
        ub = P.enc_vec(u_)
        for w in range(4):
            r0, r1 = [], []
            for off, dst in ((0, r0), (-1, r1)):
                vb = P.enc_poly([((D + 1) // 2 + off) % q] * 16, 16)
                m = oracle(ub + vb, w); queries += 1
                if through < 2:
                    netx = Net(3, q); rx = Rounder(netx, q, D)
                    assert signed(q, netx.open(decrypt(netx, rx, deal(netx, s), ub + vb, w), 'M')) == m; through += 1
                dst.extend(m)
            for i in range(16):
                rec[64 * j + 16 * w + i] = -1 if r1[i] == 1 else (0 if r0[i] == 1 else 1)
