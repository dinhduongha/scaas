// ua-mtx-merge T20 Step 1: the five wallet-display requests, derived from the generated vector rows through the generators'
// own builders (clients/clientkeys/src/evm.js), never by hand. Per row: rebuild the vector's typed data at its own context A
// (chain 31337) and require the vector's digest (the builder path reproduces the generator), then apply the named overrides
// and build again on context B of ua/structures.json (chain 7622, SCaaS testnet: MetaMask signs typed data only for the
// active chain id). The overrides are listed in each row of rows.json.
//   node docs/research/ua-mtx-merge-wallet-display/derive.mjs   (writes rows.json beside this file)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { hex } from '../../../clients/clientkeys/src/bytes.js';
import { TYPED_OPS, OP_BUILDERS, hashTypedData, uaMetaTransferTypedData, uaTradeOrderTypedData }
  from '../../../clients/clientkeys/src/evm.js';

const V = (p) => JSON.parse(readFileSync(fileURLToPath(new URL(`../../../smartcontracts/vectors/${p}`, import.meta.url)), 'utf8'));
const ZERO = '0x' + '00'.repeat(20);
const { contexts } = V('ua/structures.json');
const typedOps = V('typed/typed_ops.json');
const metatx3 = V('ua/metatx3.json');
const uatrade = V('ua/uatrade_kat.json');

const fail = (m) => { throw new Error(m); };
const byName = (rows, name) => rows.find((r) => r.name === name) ?? fail(`no row ${name}`);
// mode bit 0 is MODE_RESTRICT_RELAYER (MetaTxLib.canon): cleared, the relayer is unbound and hashed as 0
const unbind = (m) => ({ ...m, mode: m.mode & ~1, relayer: ZERO });

// Each source: the vector row, its digest, and build(ctx, message) through the builder its generator uses.
const op = (name, kind) => {
  const row = typedOps.ops[name];
  const d = row.domains[kind];
  const build = (ctx, message) => OP_BUILDERS[`${TYPED_OPS[name].builder}TypedData`]({ name: d.domain.name,
    contract: d.domain.verifyingContract, chainId: ctx.chainId, chainUid: ctx.chainUid, message });
  return { source: `typed/typed_ops.json ops.${name} domains.${kind}`, message: row.message, digest: d.digest, build };
};
const transfer = byName(metatx3.transfer, 'native');
const order = byName(uatrade.rows, 'native');
const DESTINATION = byName(uatrade.rows, 'webauthn-p256').from; // a derived UA of the same file: 32 bytes, top bits non-zero

const SOURCES = [
  { id: 'UAMetaTransfer', source: 'ua/metatx3.json transfer[native]', message: transfer.typedData.message, digest: transfer.digest,
    build: (ctx, message) => uaMetaTransferTypedData({ contract: transfer.typedData.domain.verifyingContract, chainId: ctx.chainId,
      chainUid: ctx.chainUid, message }),
    overrides: { relayer: 'unbound (mode bit 0 cleared, relayer 0)' }, change: unbind },
  { id: 'UASetMandate', ...op('UASetMandate', 'wallet'),
    overrides: { relayer: 'unbound (mode bit 0 cleared, relayer 0)' }, change: unbind },
  { id: 'UATradeOrder', source: 'ua/uatrade_kat.json rows[native].order', message: order.order.message, digest: order.orderHash,
    build: (ctx, message) => uaTradeOrderTypedData({ token: order.order.domain.verifyingContract, chainId: ctx.chainId,
      chainUid: ctx.chainUid, order: message }),
    overrides: { relayer: 'open (0: any submitter, TradeLib)', destination: 'the from of rows[webauthn-p256] (a derived UA)' },
    change: (m) => ({ ...m, relayer: ZERO, destination: DESTINATION }) },
  { id: 'UARelayFee', ...op('UARelayFee', 'token'),
    overrides: { relayer: 'kept: the RelayFeeRouter by construction (CTR-MTX-27, msg.sender of the payment); no unbound form' },
    change: (m) => m },
  { id: 'UAPayUnderMandate', ...op('UAPayUnderMandate', 'wallet'),
    overrides: { relayer: 'unbound (mode bit 0 cleared, relayer 0)' }, change: unbind },
];

const B = contexts.B;
const rows = SOURCES.map((s) => {
  const again = hex(hashTypedData(s.build(contexts.A, s.message)));
  if (again !== s.digest) fail(`${s.id}: the builder gives ${again}, the vector ${s.digest}`);
  const typedData = s.build(B, s.change(s.message));
  if (s.id !== 'UARelayFee' && BigInt(typedData.message.relayer) !== 0n) fail(`${s.id}: relayer not 0`);
  return { id: s.id, source: `smartcontracts/vectors/${s.source}`, sourceDigest: s.digest, overrides: { chainId: 'context B', ...s.overrides },
    typedData, digest: hex(hashTypedData(typedData)) };
});

const out = {
  note: 'Generated by docs/research/ua-mtx-merge-wallet-display/derive.mjs (clients/clientkeys/src/evm.js builders); never edit by '
    + 'hand. Each row: its vector source rebuilt at context A reproduces sourceDigest; typedData is the same row on context B of '
    + 'ua/structures.json with the listed overrides; digest is hashTypedData(typedData). Not for submission: fillers stay fillers.',
  chainId: B.chainId, chainUid: B.chainUid, rows,
};
writeFileSync(fileURLToPath(new URL('rows.json', import.meta.url)), JSON.stringify(out, null, 2) + '\n');
for (const r of rows) console.log(`${r.id.padEnd(18)} ${r.digest}`);
