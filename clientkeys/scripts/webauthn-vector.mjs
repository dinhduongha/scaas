// Generates smartcontracts/evm/test/vectors/webauthn_soft.json: a WebAuthn assertion from the software
// authenticator (Node WebCrypto P-256, fixed key, DER signature) pushed through the SAME client path
// the portal uses (derToRS + low-s, encodeAssertion, accountSignature). We retry until WebCrypto
// returns a HIGH-s DER signature, so the forge test proves the normalised form verifies on-chain.
//   node scripts/webauthn-vector.mjs
import { writeFileSync } from 'node:fs';
import { p256 } from '@noble/curves/nist.js';
import { softAuthenticator } from '../test/softauthn.js';
import { derToRS, encodeAssertion, publicKeyFromSpki } from '../src/webauthn.js';
import { accountSignature } from '../src/evm.js';
import { hex, b64url, keccak_256, utf8ToBytes } from '../src/bytes.js';

const d = keccak_256(utf8ToBytes('bamboo clientkeys webauthn vector key'));
const pub = p256.getPublicKey(d, false);
const jwk = { kty: 'EC', crv: 'P-256', d: b64url(d), x: b64url(pub.subarray(1, 33)), y: b64url(pub.subarray(33)), ext: true };
const rpId = 'portal.bamboo.test';
const origin = 'https://portal.bamboo.test';
const auth = await softAuthenticator({ rpId, origin, jwk });
const { x, y } = publicKeyFromSpki(auth.spki);
const challenge = keccak_256(utf8ToBytes('MetaTransaction digest stand-in'));

let a;
for (;;) {
  a = await auth.get(challenge, { flags: 0x1d });          // UP|UV|BE|BS: a synced passkey
  if (derToRS(a.signature).highS) break;
}
const out = {
  note: 'Generated by clientkeys/scripts/webauthn-vector.mjs (software authenticator, WebCrypto P-256). DER had high s; '
    + 'signature = abi.encode(keyIndex 0, proof [], abi.encode(authenticatorData, clientDataJSON, r, low s)).',
  rpId, origin, qx: hex(x), qy: hex(y), challenge: hex(challenge),
  authenticatorData: hex(a.authenticatorData), clientDataJSON: new TextDecoder().decode(a.clientDataJSON),
  signatureDer: hex(a.signature), derWasHighS: true,
  signature: hex(accountSignature(0, [], encodeAssertion(a))),
};
const path = new URL('../../smartcontracts/evm/test/vectors/webauthn_soft.json', import.meta.url);
writeFileSync(path, JSON.stringify(out, null, 2) + '\n');
console.log('wrote', path.pathname);
