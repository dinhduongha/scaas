/// A read's mark.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Trust {
    /// `Purpose::FeedsDecryption` (CLI-RPC-06): never a discovered endpoint alone
    Trusted,
    /// `Purpose::Plain`: a read that chooses nothing
    Plain,
}

