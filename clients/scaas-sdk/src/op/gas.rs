//! The gas of a relayed operation's quote (owner 2026-11-18, ruling 1; owner 2026-11-19, ruling B; spec §13.3): a quote never
//! makes or sends a signature, so its gas comes from a table keyed by what changes the cost: the entry, the domain kind, the
//! signer's kind and whether the lane is used for the first time. A key without a row is `GasUnquoted` at quote time (an
//! estimate of the unsigned form misses the signature's verification, which is what differs most between signer kinds). The
//! profile's own rows ([`GasRow`], measured for its chain) come first, then the built-in rows below. `submit` then signs
//! once, writes the row and simulates the signed calldata; a need above the confirmed quote is `SimRefused` (ruling A).
//!
//! PLANNED (ruling B, after the pre-freeze matrix): the built-in rows are generated by a forge gas test that sends exactly what
//! the SDK sends (its calldata per entry, each signer kind, a fresh and a used lane, `entryRef = 0` for a transfer), on the
//! Amsterdam settings of `foundry.toml`; until then the rows are the committed pins named beside each, and every other key is
//! unquoted.
use crate::GasRow;

/// A native EVM key's signer kind in the table.
pub const NATIVE_EVM: u16 = 0;

/// The built-in rows `(entry, kind, signer, fresh, gas, measured)`, each from a committed pin
/// (`smartcontracts/evm/test/vectors/plus_zero_gas.json`, written by `test/governance/PlusZero.t.sol`, moved only with old → new
/// in a contracts commit): `measured` names the pin's rows, `gas` is the worst of them rounded up to the next multiple of 1,000
/// (owner 2026-11-19, ruling B: an exact multiple stays); the test `built_in_rows_cover_their_pins` holds each row to
/// `measured <= gas < measured + 1000`. Every pin was measured with `entryRef = 0` on a lane primed before (not fresh).
type BuiltIn = (
    &'static str,
    &'static str,
    u16,
    bool,
    u64,
    &'static [&'static str],
);
const BUILT_IN: &[BuiltIn] = &[
    // 97_947 (normal 97_871): a P-256 UA (0x0101) on the fixture's stand-in verifier
    (
        "mtxExecuteTransfer",
        "token",
        0x0101,
        false,
        98_000,
        &["uaExecuteTransfer_normal", "uaExecuteTransfer_wrapped"],
    ),
    // 139_535 (normal 139_522): a zether-bls12381 UA (0x0141), the real verifier
    (
        "mtxExecuteTransfer",
        "zether",
        0x0141,
        false,
        140_000,
        &[
            "uaExecuteTransfer_normalZether",
            "uaExecuteTransfer_wrappedZether",
        ],
    ),
    // 265_112 both: an mldsa65 UA (0x0131), the precompile candidate mocked
    (
        "mtxExecuteTransfer",
        "pqz",
        0x0131,
        false,
        266_000,
        &[
            "uaExecuteTransfer_normalPqz",
            "uaExecuteTransfer_wrappedPqz",
        ],
    ),
    // 72_600: the router's inherited ordered cancel signed by an EOA (a native EVM key)
    (
        "mtxCancelNonce",
        "gov_router",
        NATIVE_EVM,
        false,
        73_000,
        &["mtxCancelNonce_router"],
    ),
];

/// The transaction's base cost and calldata at the highest price per byte (EIP-7976's floor, 64 gas a byte).
const INTRINSIC: u64 = 21_000;
const PER_BYTE: u64 = 64;

/// The stated margin: the figure plus half of it.
pub(crate) fn with_margin(g: u64) -> u64 {
    g.saturating_add(g / 2)
}

/// The execution gas of the key: the profile's row, else the built-in one; `None`: unquoted.
pub(crate) fn lookup(
    profile: &[GasRow],
    entry: &str,
    kind: &str,
    signer: u16,
    fresh: bool,
) -> Option<u64> {
    profile
        .iter()
        .find(|r| r.entry == entry && r.kind == kind && r.signer == signer && r.fresh == fresh)
        .map(|r| r.gas)
        .or_else(|| {
            BUILT_IN
                .iter()
                .find(|(e, k, s, f, _, _)| *e == entry && *k == kind && *s == signer && *f == fresh)
                .map(|r| r.4)
        })
}

/// The quote's gas limit of a key whose unsigned calldata is `len` bytes, with the margin; `None`: unquoted.
pub(crate) fn quoted(
    profile: &[GasRow],
    entry: &str,
    kind: &str,
    signer: u16,
    fresh: bool,
    len: usize,
) -> Option<u64> {
    let g = lookup(profile, entry, kind, signer, fresh)?;
    let bytes = u64::try_from(len)
        .unwrap_or(u64::MAX)
        .saturating_mul(PER_BYTE);
    Some(with_margin(
        g.saturating_add(INTRINSIC).saturating_add(bytes),
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Ruling B: the key is the whole tuple; a profile row comes first; every other key is unquoted.
    #[test]
    fn gas_table_lookup_by_the_whole_key() {
        assert_eq!(
            lookup(&[], "mtxExecuteTransfer", "token", 0x0101, false),
            Some(98_000)
        );
        // the same entry by another signer kind, on a fresh lane, in another domain: no row
        assert_eq!(
            lookup(&[], "mtxExecuteTransfer", "token", 0x0131, false),
            None
        );
        assert_eq!(
            lookup(&[], "mtxExecuteTransfer", "token", 0x0101, true),
            None
        );
        assert_eq!(
            lookup(&[], "mtxExecuteTransfer", "wallet", 0x0101, false),
            None
        );
        assert_eq!(lookup(&[], "mtxCancelNonce", "token", 0x0101, false), None);
        let own = GasRow {
            entry: "mtxExecuteTransfer".into(),
            kind: "token".into(),
            signer: 0x0101,
            fresh: false,
            gas: 300_000,
        };
        assert_eq!(
            lookup(
                std::slice::from_ref(&own),
                "mtxExecuteTransfer",
                "token",
                0x0101,
                false
            ),
            Some(300_000),
            "the profile's row first"
        );
        assert_eq!(
            quoted(&[], "mtxCancelNonce", "gov_router", NATIVE_EVM, false, 10),
            Some((73_000 + 21_000 + 640) * 3 / 2)
        );
    }

    /// Ruling B's check: each built-in row covers its pins' worst figure and stays within 1,000 of it (an undershoot fails
    /// closed, a stale overestimate is caught), read from the committed pin file.
    #[test]
    #[allow(clippy::unwrap_used, clippy::indexing_slicing)]
    fn built_in_rows_cover_their_pins() {
        let path = concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/../../smartcontracts/evm/test/vectors/plus_zero_gas.json"
        );
        let pins: serde_json::Value =
            serde_json::from_str(&std::fs::read_to_string(path).unwrap()).unwrap();
        for (entry, kind, _, _, gas, measured) in BUILT_IN {
            let worst = measured
                .iter()
                .map(|m| pins[*m].as_u64().unwrap())
                .max()
                .unwrap();
            assert!(
                worst <= *gas && *gas - worst < 1_000,
                "{entry} on {kind}: {gas} for {worst}"
            );
            assert_eq!(gas % 1_000, 0, "{entry} on {kind}: a multiple of 1,000");
        }
    }
}
