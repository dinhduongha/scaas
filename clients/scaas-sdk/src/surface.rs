//! The SDK's typed entry points (spec §21; plan T18): every `(struct, domain kind)` pair of
//! `smartcontracts/vectors/typed/typed_ops.json` with the one function that prepares (or signs) it, its module and its feature.
//! `tests/completeness.rs` holds this table equal to the vectors both ways and each function to its module's source. The
//! named exclusions: [`EXCLUDED`] (no entry of its own) and [`PLANNED`] (no entry yet, its reason in the decisions).

/// One entry point and the pairs it prepares.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct EntryPoint {
    pub function: &'static str,
    pub module: &'static str,
    pub feature: &'static str,
    pub pairs: &'static [(&'static str, &'static str)],
}

/// Pairs no SDK function prepares by design: `PqzAuth` is attached by the PQZ facade to a debit (no `abi`, no entry).
pub const EXCLUDED: &[(&str, &str)] = &[("PqzAuth", "pqz")];

/// Pairs without an entry point yet: `PqzRollOver` waits with the opening-token reads and the scoped key's debit (P-T16-7,
/// decisions CLI-SDK-30, PLANNED).
pub const PLANNED: &[(&str, &str)] = &[("PqzRollOver", "pqz")];

