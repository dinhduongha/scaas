// ------------------------------------------------------------------ a personal vault (one member, one wrap: ruling (a))
function personalVault(tag, who, mode, pass, items) {
  const home = mode === 0 ? HOME0 : { homeChain: B.chainUid, homeVaultContract: B.verifyingContract };
  const ds = pv.domainOf(mode, B);
  const nonce = nonce53(`${tag}/nonce`);
  const vid = hex(pv.vaultId(who.ua, nonce, mode, home.homeChain, home.homeVaultContract));
  const e0 = `${tag}/epoch-0`;
  const k0 = epochKeys(e0, { vid, eid: vid, epoch: 0, ...pass, info: { name: tag, shared: false } });
  const members = [mk(who)];
  const create = {
    creator: who.ua,
    nonce,
    mode,
    ...home,
    admins: [who.ua],
    members,
    wrapHashes: wraps(e0, k0.Ke, vid, vid, members),
    passKdf: pass.passKdf,
    passSalt: pass.passSalt,
    sealedInfo: k0.sealedInfo,
  };
  const recs = [
    recordRow(`${tag}.create`, "PqVaultCreate", create, who, ds, { id: vid, scope: hex(pv.scopeVault(who.ua)) }),
  ];
  items(vid, home).forEach(([n, content], i) => {
    const iid = hex(pv.itemId(vid, who.ua, n));
    const x = { vaultId: vid, epochId: vid, itemId: iid, version: 1, author: who.ua, ...home };
    const it = {
      vaultId: vid,
      epochId: vid,
      author: who.ua,
      nonce: n,
      ciphertext: itemCt(`${tag}/item-${i}`, x, content, {
        epochName: e0,
        record: `${tag}.item-${i}`,
        creator: who.ua,
        mode,
      }),
    };
    recs.push(
      recordRow(`${tag}.item-${i}`, "PqVaultItem", it, who, ds, { id: iid, scope: hex(pv.scopeItem(vid, who.ua)) }),
    );
  });
  vaults.push({ name: tag, mode, vaultId: vid, ...home, records: recs });
  return { vid, home };
}

