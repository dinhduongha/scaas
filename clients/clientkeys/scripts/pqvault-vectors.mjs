const rnd = (name, n = 32) => {
  const blocks = [];
  for (let i = 0; 32 * i < n; i++) blocks.push(keccak_256(utf8ToBytes(`scaas/pqvault/vectors/${name}/${i}`)));
  return concatBytes(...blocks).slice(0, n);
};
/** A creation nonce: 53 random bits (a JSON number stays exact; the contract takes any uint64). */
const nonce53 = (name) => Number(BigInt(hex(rnd(name, 8))) >> 11n);
const must = (c, what) => {
  if (!c) throw new Error(`pqvault vectors: ${what}`);
};
const refused = (f) => {
  try {
    f();
  } catch (e) {
    return e.code ?? e.message;
  }
  return null;
};
