const sign = (who, struct, s, ds) => {
  const signature = signUA(who.kindName, who.secretKey, pv.P_V, pv.typed(struct, s, ds), { extraEntropy: false });
  must(verifyUA(who.kindName, who.publicKey, pv.P_V, pv.typed(struct, s, ds), signature), `${who.name} ${struct}`);
  return { keyData: "0x", signature: hex(signature), members: [] };
};

