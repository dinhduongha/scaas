function passKeyRow(epochName, passKdf, passphrase, passSalt) {
  if (passKdf === 0) return null;
  const Pk = pv.passKey(passKdf, passphrase, passSalt);
  passRows.push({
    name: epochName,
    epoch: epochName,
    passKdf,
    passphrase,
    passphraseUtf8: hex(utf8ToBytes(passphrase)),
    passSalt,
    Pk: hex(Pk.key),
  });
  return Pk;
}

function wraps(epochName, Ke, vid, eid, members) {
  return members.map((m) => {
    const p = everyone.find((x) => x.ua === m.ua);
    const mlkemM = rnd(`wrap/${epochName}/${p.name}/mlkem-m`);
    const x25519Secret = rnd(`wrap/${epochName}/${p.name}/x25519-ephemeral-secret`);
    const w = pv.wrapTo({
      Ke,
      vaultId: vid,
      epochId: eid,
      member: m.ua,
      keyId: m.keyId,
      kemPk: p.kem.kemPk,
      m: mlkemM,
      x25519Secret,
    });
    const row = {
      name: `${epochName}/${p.name}`,
      kemKey: p.name,
      Ke: hex(Ke),
      vaultId: vid,
      epochId: eid,
      member: m.ua,
      keyId: m.keyId,
      mlkemM,
      x25519Secret,
      ss: w.ss,
      kek: w.kek,
      sealedKey: w.sealedKey,
      wrap: w.wrap,
      hashStruct: pv.structHash("Wrap", w.wrap),
    };
    wrapRows.push(row);
    return hex(row.hashStruct);
  });
}

/** One epoch's keys: K_e, P_k, K_v, sealedInfo (with `prev` when `prev` names an earlier epoch). */
function epochKeys(name, { vid, eid, epoch, passKdf, passphrase, passSalt, info, prev }) {
  const Ke = rnd(`K_e/${name}`);
  const Pk = passKeyRow(name, passKdf, passphrase, passSalt);
  const Kv = pv.vaultKey(D(Ke), Pk, vid, eid, passKdf);
  Kvs[name] = Kv;
  let p = null;
  if (prev) {
    const nonce = rnd(`nonce/keywrap/${name}`, 12);
    const keyWrap = pv.keyWrap(Kv, vid, eid, prev.epochId, Kvs[prev.epoch], nonce);
    p = {
      epoch: prev.epoch,
      epochId: prev.epochId,
      kPrev: hex(pv.prevKey(Kv, vid, eid, prev.epochId).key),
      nonce: hex(nonce),
      keyWrap: hex(keyWrap),
    };
    info = { ...info, prev: { epochId: prev.epochId, keyWrap: hex(keyWrap) } };
  }
  const infoNonce = rnd(`nonce/sealed-info/${name}`, 12);
  const s = pv.sealInfo(Kv, vid, eid, info, infoNonce);
  epochRows.push({
    name,
    vaultId: vid,
    epochId: eid,
    epoch,
    passKdf,
    passSalt,
    Ke: hex(Ke),
    Pk: Pk ? hex(Pk.key) : null,
    Kv: hex(Kv.key),
    kInfo: hex(s.kInfo),
    info,
    json: s.json,
    pt: hex(s.pt),
    infoNonce: hex(infoNonce),
    sealedInfo: hex(s.sealedInfo),
    prev: p,
  });
  return { Ke, Kv, sealedInfo: hex(s.sealedInfo) };
}

/** An item version's ciphertext and its row (`file`: the file key sealed under kFile is added to the content). */
function itemCt(name, x, content, { epochName, record, batchIndex, creator, mode }) {
  const Kv = Kvs[epochName];
  if (content.type === "file") {
    const fk = pv.handle(pv.USAGE.Data, rnd(`file/${name}/key`));
    const kFile = pv.fileKey(Kv, x.vaultId, x.epochId, x.itemId, x.version);
    const kw = pv.sealKey(
      kFile,
      rnd(`nonce/file/${name}`, 12),
      fk,
      pv.fileCtx(x.vaultId, x.epochId, x.itemId, x.version),
    );
    content = { ...content, keyWrap: hex(kw) };
    x = { ...x, file: { kFile: hex(kFile.key), key: hex(fk.key) } };
  }
  const json = pv.canonicalJson(content);
  const pt = pv.padItem(utf8ToBytes(json));
  const r = rnd(`r/${name}`, 16);
  const k = pv.itemKeys(Kv, r, x);
  const ciphertext = hex(pv.encryptItem(Kv, r, x, pt));
  const row = {
    name,
    record,
    ...(batchIndex === undefined ? {} : { batchIndex }),
    mode,
    creator,
    vaultId: x.vaultId,
    epochId: x.epochId,
    itemId: x.itemId,
    version: x.version,
    author: x.author,
    homeChain: x.homeChain,
    homeVaultContract: x.homeVaultContract,
    Kv: hex(Kv.key),
    r: hex(r),
    okm: hex(k.okm),
    bk: hex(k.bk.key),
    n: hex(k.n),
    aad: hex(pv.itemAad(x)),
    content,
    json,
    pt: hex(pt),
    ciphertext,
  };
  if (x.file) row.file = x.file;
  itemRows.push(row);
  return ciphertext;
}

/** A signed record's row in its vault's domain. */
function recordRow(name, struct, s, who, ds, extra = {}) {
  const sig = sign(who, struct, s, ds);
  const row = {
    name,
    struct,
    signer: who.name,
    record: s,
    hashStruct: hex(pv.structHash(struct, s)),
    typed: hex(pv.typed(struct, s, ds)),
    uaMessage: { kind: who.kind, digest: hex(pv.signedDigest(who.kind, struct, s, ds)) },
    uaSig: sig,
    sigHash: hex(pv.sigHash(sig)),
    ...extra,
  };
  if (["PqVaultCreate", "PqVaultEpoch", "PqVaultRemove"].includes(struct)) row.blob = hex(pv.groupBlob(struct, s, sig));
  if (struct === "PqVaultItem") row.blob = hex(pv.itemBlob(s, row.sigHash, Z32));
  if (struct === "PqVaultEdit") row.blob = hex(pv.editBlob(s, row.sigHash));
  return row;
}

