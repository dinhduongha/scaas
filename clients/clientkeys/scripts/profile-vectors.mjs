// Generates smartcontracts/vectors/profile/{ids,envelope,items,export}.json (user-profiles plan UP1; spec §4, §6, §7.1, §7.2,
// §10.1; the plan's "Pinned formats") by src/profile.js: UUIDv7 ids, name_key and the name check; the KDF bounds, the
// OpaqueString bytes, Argon2id at the default set (one row) and the test set, KEK_pass, K_plat, the sub-keys, the wraps and
// their AD, labels, whole envelope files and the wrap refusals; sealed items, their AD and HMAC file names, manifests,
// anchors and every anchorCompare case; the export header, files and every import refusal. Every random input is fixed:
// rnd(name, n) = the first n bytes of keccak256("scaas/profile/vectors/<name>/0") ‖ keccak256(".../<name>/1") ‖ …
//   node scripts/profile-vectors.mjs [outDir]
