const OUT = process.argv[2] ?? fileURLToPath(new URL("../../../smartcontracts/vectors/profile/", import.meta.url));
mkdirSync(OUT, { recursive: true });

const rnd = (name, n = 32) => {
  const blocks = [];
  for (let i = 0; 32 * i < n; i++) blocks.push(keccak_256(utf8ToBytes(`scaas/profile/vectors/${name}/${i}`)));
  return concatBytes(...blocks).slice(0, n);
};
const must = (c, what) => {
  if (!c) throw new Error(`profile vectors: ${what}`);
};
const refused = (f) => {
  try {
    f();
  } catch (e) {
    return e.reason && e.code === "ProfileImportOpen" ? `${e.code}/${e.reason}` : e.code;
  }
  return null;
};
const utf8Hex = (s) => hex(utf8ToBytes(s));
const be32 = (n) => Uint8Array.of(n >>> 24, (n >>> 16) & 255, (n >>> 8) & 255, n & 255);
const COMMON =
  "Bytes are 0x-hex, lower case; inside a file's text (envelope, item, header) bytes are base64 (RFC 4648 §4, padded). " +
  "Generated by clients/clientkeys/scripts/profile-vectors.mjs (src/profile.js); never edit by hand. Random inputs are " +
  'fixed: rnd(name, n) = the first n bytes of keccak256("scaas/profile/vectors/<name>/0") ‖ ' +
  'keccak256("scaas/profile/vectors/<name>/1") ‖ …; the labels are in the generator. Source: ' +
  "docs/superpowers/specs/2026-11-27-user-profiles.md (§4, §6, §7.1, §7.2, §10.1) and the plan " +
  'docs/superpowers/plans/2026-11-27-user-profiles.md ("Pinned formats"). UNAUDITED.';
const write = (name, comment, body) =>
  writeFileSync(join(OUT, name), JSON.stringify({ _comment: `${COMMON} ${comment}`, ...body }, null, 2) + "\n");

