const rnd = (name, n = 32) => {
  const blocks = [];
  for (let i = 0; 32 * i < n; i++) blocks.push(keccak_256(utf8ToBytes(`scaas/pqchat/vectors/${name}/${i}`)));
  return concatBytes(...blocks).slice(0, n);
};
