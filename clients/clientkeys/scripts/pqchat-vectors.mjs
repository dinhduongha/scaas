const wrapRows = [];
function wraps(epochName, K, sid, eid, members) {
  return members.map((mem) => {
    const p = people.find((x) => x.ua === mem.ua);
    const mlkemM = rnd(`wrap/${epochName}/${p.name}/mlkem-m`);
    const x25519Secret = rnd(`wrap/${epochName}/${p.name}/x25519-ephemeral-secret`);
    const w = pc.wrapTo({ K, sessionId: sid, epochId: eid, member: mem.ua, keyId: mem.keyId, kemPk: p.kem.kemPk, m: mlkemM, x25519Secret });
    const row = { name: `${epochName}/${p.name}`, kemKey: p.name, K, sessionId: sid, epochId: eid, member: mem.ua, keyId: mem.keyId,
      mlkemM, x25519Secret, ctM: w.ctM, ssM: w.ssM, E: w.E, ssX: w.ssX, ss: w.ss, kek: w.kek, sealedKey: w.sealedKey, wrap: w.wrap,
      hashStruct: pc.structHash('Wrap', w.wrap) };
    wrapRows.push(row);
    return row.hashStruct;
  });
}
const sealedRows = [];
function sealed(name, K, sid, eid, info) {
  const nonce = rnd(`nonce/sealed-info/${name}`, 12);
  const s = pc.sealInfo(K, sid, eid, info, nonce);
  sealedRows.push({ name, K, sessionId: sid, epochId: eid, info, json: s.json, pt: s.pt, kInfo: s.kInfo, nonce, sealedInfo: s.sealedInfo });
  return s.sealedInfo;
}

