// ---- Solana: find_program_address and the Account's ["acct", owner] address
const pdaRow = (seeds, program) => {
  const { address, bump } = sol.findPda(seeds, program);
  return { seeds: seeds.map(hex), program: base58.encode(program), address: base58.encode(address), bump };
};
const pda = [
  pdaRow([], rnd("sol/program/0")),
  pdaRow([utf8ToBytes("config")], rnd("sol/program/0")),
  pdaRow([rnd("sol/seed/32")], rnd("sol/program/1")),
  pdaRow([new Uint8Array(0)], rnd("sol/program/1")),
  pdaRow(
    Array.from({ length: sol.MAX_SEEDS - 1 }, (_, i) => rnd(`sol/seed/many/${i}`)),
    rnd("sol/program/2"),
  ),
];
// the first seeds (by index) whose bump is below 255 and below 254: the search past an on-curve hash
for (const want of [254, 253]) {
  for (let i = 0; ; i++) {
    const r = pdaRow([utf8ToBytes(`bump/${i}`)], rnd("sol/program/0"));
    if (r.bump === want) {
      pda.push(r);
      break;
    }
  }
}
must(
  pda.some((r) => r.bump < 255),
  "a row past an on-curve hash",
);
const account = [0, 1, 2, 3].map((i) => {
  const program = rnd(`sol/acct/program/${i % 2}`);
  const owner = rnd(`sol/acct/owner/${i}`);
  return {
    program: base58.encode(program),
    owner: base58.encode(owner),
    account: base58.encode(sol.accountOf(program, owner)),
    bump: sol.findPda([utf8ToBytes("acct"), owner], program).bump,
  };
});
// refused: one change each from a valid input
const refused = [
  {
    why: "16 seeds (the bump would be the 17th)",
    seeds: Array.from({ length: 16 }, () => "0x"),
    program: hex(rnd("sol/program/0")),
  },
  { why: "a seed of 33 bytes", seeds: [hex(new Uint8Array(33))], program: hex(rnd("sol/program/0")) },
  { why: "a program of 31 bytes", seeds: [], program: hex(rnd("sol/program/0").slice(0, 31)) },
];
for (const r of refused)
  must(
    (() => {
      try {
        sol.findPda(r.seeds.map(fromHex), fromHex(r.program));
        return false;
      } catch (e) {
        return e instanceof sol.SolanaError;
      }
    })(),
    `refused: ${r.why}`,
  );

