// Generates smartcontracts/vectors/families/<family>.json (plan 2026-11-17-scaas-sdk T24, T27) from src/fam/<family>.js, read by
// clientkeys' tests, ua-rs and scaas-node's adapter tests. Every input is fixed:
// rnd(name) = keccak256("scaas/families/vectors/<name>"). Deterministic: two runs write the same bytes.
//   node scripts/families-vectors.mjs [outDir]
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { base58 } from "@scure/base";
import * as sol from "../src/fam/solana.js";
import { hex, fromHex, keccak_256, utf8ToBytes } from "../src/bytes.js";

const OUT = process.argv[2] ?? fileURLToPath(new URL("../../../smartcontracts/vectors/families/", import.meta.url));
mkdirSync(OUT, { recursive: true });
const rnd = (name) => keccak_256(utf8ToBytes(`scaas/families/vectors/${name}`));
const must = (c, what) => {
  if (!c) throw new Error(`families-vectors: ${what}`);
};

// ---- Solana: find_program_address and the Account's ["acct", owner] address
const pdaRow = (seeds, program) => {
  const { address, bump } = sol.findPda(seeds, program);
  return { seeds: seeds.map(hex), program: base58.encode(program), address: base58.encode(address), bump };
};
const pda = [
  pdaRow([], rnd("sol/program/0")),
  pdaRow([utf8ToBytes("config")], rnd("sol/program/0")),
  pdaRow([rnd("sol/seed/32")], rnd("sol/program/1")),
  pdaRow([new Uint8Array(0)], rnd("sol/program/1")),
  pdaRow(
    Array.from({ length: sol.MAX_SEEDS - 1 }, (_, i) => rnd(`sol/seed/many/${i}`)),
    rnd("sol/program/2"),
  ),
];
// the first seeds (by index) whose bump is below 255 and below 254: the search past an on-curve hash
for (const want of [254, 253]) {
  for (let i = 0; ; i++) {
    const r = pdaRow([utf8ToBytes(`bump/${i}`)], rnd("sol/program/0"));
    if (r.bump === want) {
      pda.push(r);
      break;
    }
  }
}
must(pda.some((r) => r.bump < 255), "a row past an on-curve hash");
const account = [0, 1, 2, 3].map((i) => {
  const program = rnd(`sol/acct/program/${i % 2}`);
  const owner = rnd(`sol/acct/owner/${i}`);
  return {
    program: base58.encode(program),
    owner: base58.encode(owner),
    account: base58.encode(sol.accountOf(program, owner)),
    bump: sol.findPda([utf8ToBytes("acct"), owner], program).bump,
  };
});
// refused: one change each from a valid input
const refused = [
  { why: "16 seeds (the bump would be the 17th)", seeds: Array.from({ length: 16 }, () => "0x"), program: hex(rnd("sol/program/0")) },
  { why: "a seed of 33 bytes", seeds: [hex(new Uint8Array(33))], program: hex(rnd("sol/program/0")) },
  { why: "a program of 31 bytes", seeds: [], program: hex(rnd("sol/program/0").slice(0, 31)) },
];
for (const r of refused)
  must(
    (() => {
      try {
        sol.findPda(r.seeds.map(fromHex), fromHex(r.program));
        return false;
      } catch (e) {
        return e instanceof sol.SolanaError;
      }
    })(),
    `refused: ${r.why}`,
  );

const solana = {
  note: "Generated by clients/clientkeys/scripts/families-vectors.mjs from src/fam/solana.js; never edit by hand. pda: Pubkey::find_program_address(seeds, program) (seeds hex, addresses base58; bump from 255 down, the first sha256(seeds ‖ bump ‖ program ‖ \"ProgramDerivedAddress\") off the ed25519 curve as curve25519-dalek decompresses). account: the SCaaS Account of owner, seeds [\"acct\", owner] (scaas-node adapters/solana.rs account_of). refused: inputs Solana refuses (at most 15 seeds beside the bump, 32 bytes each; a 32-byte program).",
  pda,
  account,
  refused,
};
writeFileSync(join(OUT, "solana.json"), JSON.stringify(solana, null, 1) + "\n");
console.log(`wrote ${join(OUT, "solana.json")}`);
