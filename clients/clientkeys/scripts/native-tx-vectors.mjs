// Generates smartcontracts/vectors/native/<family>-tx.json (plan 2026-11-17-scaas-sdk T41, spec §27.5 (d)): each family's native
// transaction from named fields, the bytes, the id and a seed-signed envelope, and a refused row per must-check; read by
// clientkeys' tests, ua-rs (byte-equal) and scaas-node (the official XDR crate's decode). Fixed inputs: the BIP-39 test mnemonic,
// rnd(name) = keccak256("scaas/native/vectors/<name>"). Deterministic: two runs write the same bytes.
//   node scripts/native-tx-vectors.mjs [outDir]
import { mkdirSync, writeFileSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import * as sor from "../src/fam/soroban.js";
import { seedFromWords, deriveKey, signStellarTransaction } from "../src/seed.js";
import { hex, keccak_256, utf8ToBytes } from "../src/bytes.js";

const OUT = process.argv[2] ?? fileURLToPath(new URL("../../../smartcontracts/vectors/native/", import.meta.url));
mkdirSync(OUT, { recursive: true });
const rnd = (name) => keccak_256(utf8ToBytes(`scaas/native/vectors/${name}`));
const b64 = (b) => Buffer.from(b).toString("base64");
const must = (c, what) => {
  if (!c) throw new Error(`native-tx-vectors: ${what}`);
};

// ---- Soroban: the self-relay of T27's signed pay (families/soroban.json) and a plain XLM payment
const fam = JSON.parse(
  readFileSync(new URL("../../../smartcontracts/vectors/families/soroban.json", import.meta.url), "utf8"),
);
const seed = seedFromWords(fam.mnemonic);
const payer = deriveKey(seed, "stellar", 2);
const passphrase = fam.ops[0].shown.passphrase;
const networkId = hex(sor.networkIdOf(passphrase));
const pay = fam.ops.find((o) => o.kind === "pay");
const op = pay.signed_op;
const f = pay.terms.fields;
const data = (archived = []) => ({
  readOnly: [b64(sor.instanceKey(fam.token)), b64(sor.codeKey(hex(rnd("sor/wasm"))))],
  readWrite: [
    b64(sor.balanceKey(fam.token, f.from)),
    b64(sor.balanceKey(fam.token, f.to)),
    b64(sor.payRefKey(fam.token, f.from, f.pay_ref)),
    b64(sor.nonceKey(f.from, op.payload.nonce)),
  ],
  instructions: 4_200_000,
  diskReadBytes: 1_024,
  writeBytes: 512,
  resourceFee: "1234567",
  archived,
});
const invoke = (over = {}) => ({
  source: payer.address,
  fee: 1_234_667,
  seq: "4294967297",
  minTime: 0,
  maxTime: 1790000300,
  op: {
    invoke: {
      invocation: op.payload.invocation,
      auth: [{ payload: op.payload, from: op.from, signature: op.signature }],
      data: data(),
    },
  },
  ...over,
});
const payment = (over = {}) => ({
  source: payer.address,
  fee: 100,
  seq: "4294967298",
  minTime: 0,
  maxTime: 1790000300,
  op: { payment: { destination: f.to, amount: "25000000" } },
  ...over,
});
const row = (what, t) => {
  const tx = sor.nativeTx(t);
  const sig = hex(signStellarTransaction(payer, sor.networkIdOf(passphrase), tx, { allowRawDigest: true }));
  return {
    what,
    ...t,
    ...(t.op.invoke ? { dataXdr: hex(sor.sorobanData(t.op.invoke.data)) } : {}),
    tx: hex(tx),
    hash: hex(sor.txHash(networkId, tx)),
    signature: sig,
    envelope: hex(sor.envelope(tx, payer.address, sig)),
  };
};
const withData = (d) => invoke({ op: { invoke: { ...invoke().op.invoke, data: d } } });
const rows = [
  row("the self-relay of a signed pay (T27's row), ext v0", invoke()),
  row("the same with archived entries to restore (ext v1)", withData(data([1, 3]))),
  row("a native XLM payment", payment()),
  row(
    "a payment of i64 max with a time window",
    payment({ minTime: 1789999000, op: { payment: { destination: f.to, amount: String((1n << 63n) - 1n) } } }),
  ),
];
const refused = [
  { why: "a sequence of 0", t: payment({ seq: "0" }) },
  { why: "no time bound (max_time 0)", t: payment({ maxTime: 0 }) },
  { why: "min_time after max_time", t: payment({ minTime: 1790000301 }) },
  { why: "a payment of 0", t: payment({ op: { payment: { destination: f.to, amount: "0" } } }) },
  { why: "a payment above i64", t: payment({ op: { payment: { destination: f.to, amount: String(1n << 63n) } } }) },
  { why: "a fee above u32", t: payment({ fee: 2 ** 32 }) },
  { why: "a source that is a C…", t: payment({ source: fam.token }) },
  {
    why: "a host call with a sub-invocation",
    t: invoke({
      op: {
        invoke: {
          ...invoke().op.invoke,
          invocation: { ...op.payload.invocation, sub_invocations: [op.payload.invocation] },
        },
      },
    }),
  },
];
for (const r of refused)
  must(
    (() => {
      try {
        sor.nativeTx(r.t);
        return false;
      } catch (e) {
        return e instanceof sor.SorobanError;
      }
    })(),
    `refused: ${r.why}`,
  );
const soroban = {
  note: "Generated by clients/clientkeys/scripts/native-tx-vectors.mjs from src/fam/soroban.js; never edit by hand. rows: nativeTx(named fields) as Transaction XDR (tx), its id sha256(network_id ‖ ENVELOPE_TYPE_TX ‖ tx) (hash), the payer's ed25519 signature over the id (the payer: m/44'/148'/2' of families/soroban.json's mnemonic) and the TransactionEnvelope v1 (envelope); dataXdr: the SorobanTransactionData XDR alone; footprint keys base64 LedgerKey XDR. refused: one must-check failed each.",
  passphrase,
  networkId,
  payer: payer.address,
  rows,
  refused: refused.map(({ why, t }) => ({ why, ...t })),
};
writeFileSync(join(OUT, "soroban-tx.json"), JSON.stringify(soroban, null, 1) + "\n");
console.log(`wrote ${join(OUT, "soroban-tx.json")}`);
