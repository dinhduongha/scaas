// Generates smartcontracts/vectors/keys/bip85.json (scaas-sdk plan T5; spec §6.4): the BIP-85 24-word children 0-2 of the
// repository mnemonic's main set and of a hidden set, and the manifest rows with and without `bip85Next` (absent when zero, so
// every earlier manifest keeps its bytes). Read back by test/bip85.test.js and clients/ua-rs/tests/bip85.rs.
// And smartcontracts/vectors/keys/roots.json (plan T6; spec §6.6): roots (c) and (d) from a fixed test key. Read back by
// test/roots.test.js and clients/ua-rs/tests/roots.rs.
//   node scripts/keys-vectors.mjs [outDir]
import { writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { hex, fromHex, concatBytes } from '../src/bytes.js';
import { secp256k1 } from '@noble/curves/secp256k1.js';
import { evmAddress, hashTypedData } from '../src/evm.js';
import {
  seedFromWords, bip85Child, entropyToWords, keyDerivationTypedData, rootFromEoaSignature, rootFromKey, signature65,
  ROOT_ARGON2, ROOT_EOA_SIG_TAG, ROOT_RAW_KEY_TAG, KEY_DERIVATION_WARNING,
} from '../src/seed.js';

const OUT = process.argv[2] ?? fileURLToPath(new URL('../../../smartcontracts/vectors/keys', import.meta.url));
const MNEMONIC = 'bench hurt jump file august wise shallow faculty impulse spring exact slush thunder author '
  + 'capable act festival slice deposit sauce coconut afford frown better';
const children = [];
for (const pass of ['', 'hidden ünï']) {
  for (const index of [0, 1, 2]) {
    const c = bip85Child(seedFromWords(MNEMONIC, pass), index);
    children.push({ bip39Passphrase: pass, index, entropy: hex(c.entropy), words: c.words.join(' ') });
  }
}
// ua-rs Manifest::to_json of a wallet with no entries, and with bip85Next after backupSenders when non-zero
const manifest = (n) => `{"v":1,"entries":[],"natives":[],"kem":[],"imports":[],"importedUas":[],"pqzHeld":[],"backupGeneration":0,"backupSenders":[]${n ? `,"bip85Next":${n}` : ''}}`;
const manifests = [0, 1, 3].map((n) => ({ bip85Next: n, json: manifest(n) }));
const refusals = [
  { id: 'index 2^31', index: 2 ** 31, error: 'Argument' },
  { id: 'index -1', index: -1, error: 'Argument' },
];
for (const r of refusals) {
  let code = null;
  try { bip85Child(seedFromWords(MNEMONIC), r.index); } catch (e) { code = e.code; }
  if (code !== r.error) throw new Error(`refusal ${r.id}: ${code}`);
}
mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, 'bip85.json'), JSON.stringify({
  note: 'Generated by clients/clientkeys/scripts/keys-vectors.mjs (scaas-sdk plan T5) from src/seed.js bip85Child; never edit by '
    + 'hand. children: BIP-85 BIP-39 24-word children m/83696968\'/39\'/0\'/24\'/<index>\' of the repository mnemonic\'s seed with '
    + 'the BIP-39 passphrase given (the SDK derives from the main set only; the hidden rows show another parent gives other '
    + 'children). manifests: ua-rs\'s manifest JSON with bip85Next, written only when non-zero, last.',
  mnemonic: MNEMONIC,
  children,
  manifests,
  refusals,
}, null, 1) + '\n');

// ---- roots (c) and (d) (plan T6)
const N = secp256k1.Point.Fn.ORDER;
const KEY = fromHex('0x4c0883a69102937d6231471b5dbb6204fe5129617082792ae468d01a3f362318'); // a test key, public knowledge
const OTHER = fromHex('0x8da4ef21b864d2cc526dbdb2a120bd2874c36c9d0a1fb7f8c63d7f7a8b41de8f'); // another test key
const account = evmAddress(secp256k1.getPublicKey(KEY, false));
const PASS = 'river-ot7ü'; // 10 code points after NFKC: the floor
/** The wallet's RFC 6979 signature `r ‖ s ‖ v` (v 27/28, low-s) of the derivation message of `set` by `key`. */
const sign = (key, set) => {
  const rec = secp256k1.sign(hashTypedData(keyDerivationTypedData(account, set)), key,
    { prehash: false, lowS: true, extraEntropy: false, format: 'recovered' });
  return concatBytes(rec.subarray(1), Uint8Array.of(27 + rec[0]));
};
const sig = sign(KEY, 0);
const highS = Uint8Array.from(sig);
highS.set(fromHex('0x' + (N - BigInt(hex(sig.subarray(32, 64)))).toString(16).padStart(64, '0')), 32);
highS[64] = 55 - sig[64]; // 27 <-> 28
const v01 = Uint8Array.from(sig);
v01[64] = sig[64] - 27;
const compact = sig.slice(0, 64);
compact[32] |= (sig[64] - 27) << 7;
const td = keyDerivationTypedData(account, 0);
const eoa = (id, s, set, extra = {}) => {
  const s65 = s.length === 64 ? signature65(s, { compact: true }) : s;
  const root = rootFromEoaSignature({ account, set, sig1: s65, sig2: s65, passphrase: PASS });
  return { id, signature: hex(s), set, ...extra, root: hex(root), words: entropyToWords(root).join(' ') };
};
const eoaRows = [
  eoa('65 bytes, low-s, v 27/28', sig, 0),
  eoa('high-s and v flipped: the same root', highS, 0),
  eoa('v in {0, 1}: the same root', v01, 0),
  eoa('64-byte EIP-2098 compact, converted explicitly: the same root', compact, 0, { compact: true }),
  eoa('another set, another root', sign(KEY, 1), 1),
];
const code = (f) => { try { f(); } catch (e) { return e.code; } return null; };
const eoaRefusals = [
  { id: 'the two signatures differ', sig1: hex(sig), sig2: hex(sign(KEY, 1)), passphrase: PASS, error: 'OriginSignature' },
  { id: 'ecrecover is another address', sig1: hex(sign(OTHER, 0)), sig2: hex(sign(OTHER, 0)), passphrase: PASS, error: 'OriginSignature' },
  { id: '64 bytes not converted', sig1: hex(compact), sig2: hex(compact), passphrase: PASS, error: 'OriginSignature' },
  { id: 's = 0', sig1: hex(concatBytes(sig.subarray(0, 32), new Uint8Array(32), sig.subarray(64))),
    sig2: hex(concatBytes(sig.subarray(0, 32), new Uint8Array(32), sig.subarray(64))), passphrase: PASS, error: 'OriginSignature' },
  { id: 'a 9-character passphrase', sig1: hex(sig), sig2: hex(sig), passphrase: 'river-ot7', error: 'DerivationPassphraseShort' },
];
for (const r of eoaRefusals) {
  const got = code(() => rootFromEoaSignature({ account, set: 0, sig1: fromHex(r.sig1), sig2: fromHex(r.sig2), passphrase: r.passphrase }));
  if (got !== r.error) throw new Error(`refusal ${r.id}: ${got}`);
}
const raw = (id, passphrase, index) => {
  const root = rootFromKey({ key: KEY, passphrase, index });
  return { id, passphrase, index, root: hex(root), words: entropyToWords(root).join(' ') };
};
const rawRows = [
  raw('empty passphrase, index 0', '', 0),
  raw('empty passphrase, index 1', '', 1),
  raw('a passphrase, index 0', PASS, 0),
];
const rawRefusals = [
  { id: 'a 9-character passphrase', key: hex(KEY), passphrase: 'river-ot7', network: 'evm', error: 'DerivationPassphraseShort' },
  { id: 'a non-EVM key', key: hex(KEY), passphrase: '', network: 'solana', error: 'Argument' },
  { id: 'key 0', key: hex(new Uint8Array(32)), passphrase: '', network: 'evm', error: 'Argument' },
];
for (const r of rawRefusals) {
  const got = code(() => rootFromKey({ key: fromHex(r.key), passphrase: r.passphrase, index: 0, network: r.network }));
  if (got !== r.error) throw new Error(`refusal ${r.id}: ${got}`);
}
writeFileSync(join(OUT, 'roots.json'), JSON.stringify({
  note: 'Generated by clients/clientkeys/scripts/keys-vectors.mjs (scaas-sdk plan T6) from src/seed.js rootFromEoaSignature / '
    + 'rootFromKey; never edit by hand. Spec §6.6 and §25 (Q-K4, Q-K5, Q-K18; owner 2026-11-17): pw = Argon2id v0x13 (m 128 MiB, '
    + 't 3, p 4, empty secret and data, 32 bytes) over the NFKC passphrase with salt keccak256(tag || address); root (c) = '
    + 'HKDF-SHA256(r || low-s s, pw, tag || u32be set, 32); root (d) = HKDF-SHA256(key, pw or SHA-256(tag) when the passphrase is '
    + 'empty, tag || u32be index, 32); words = BIP-39 of the root (24). The key is a public test key.',
  argon2: ROOT_ARGON2,
  eoaSig: { tag: ROOT_EOA_SIG_TAG, key: hex(KEY), account, passphrase: PASS, warning: KEY_DERIVATION_WARNING,
    typedData: td, digest: hex(hashTypedData(td)), rows: eoaRows, refusals: eoaRefusals },
  rawKey: { tag: ROOT_RAW_KEY_TAG, key: hex(KEY), address: account, rows: rawRows, refusals: rawRefusals },
}, null, 1) + '\n');
console.log(`keys vectors: ${children.length} children, ${manifests.length} manifests, ${eoaRows.length + rawRows.length} roots -> ${OUT}`);
