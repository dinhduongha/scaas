// Generates smartcontracts/vectors/keys/bip85.json (scaas-sdk plan T5; spec §6.4): the BIP-85 24-word children 0-2 of the
// repository mnemonic's main set and of a hidden set, and the manifest rows with and without `bip85Next` (absent when zero, so
// every earlier manifest keeps its bytes). Read back by test/bip85.test.js and clients/ua-rs/tests/bip85.rs.
//   node scripts/keys-vectors.mjs [outDir]
import { writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { hex } from '../src/bytes.js';
import { seedFromWords, bip85Child } from '../src/seed.js';

const OUT = process.argv[2] ?? fileURLToPath(new URL('../../../smartcontracts/vectors/keys', import.meta.url));
const MNEMONIC = 'bench hurt jump file august wise shallow faculty impulse spring exact slush thunder author '
  + 'capable act festival slice deposit sauce coconut afford frown better';
const children = [];
for (const pass of ['', 'hidden ünï']) {
  for (const index of [0, 1, 2]) {
    const c = bip85Child(seedFromWords(MNEMONIC, pass), index);
    children.push({ bip39Passphrase: pass, index, entropy: hex(c.entropy), words: c.words.join(' ') });
  }
}
// ua-rs Manifest::to_json of a wallet with no entries, and with bip85Next after backupSenders when non-zero
const manifest = (n) => `{"v":1,"entries":[],"natives":[],"kem":[],"imports":[],"importedUas":[],"pqzHeld":[],"backupGeneration":0,"backupSenders":[]${n ? `,"bip85Next":${n}` : ''}}`;
const manifests = [0, 1, 3].map((n) => ({ bip85Next: n, json: manifest(n) }));
const refusals = [
  { id: 'index 2^31', index: 2 ** 31, error: 'Argument' },
  { id: 'index -1', index: -1, error: 'Argument' },
];
for (const r of refusals) {
  let code = null;
  try { bip85Child(seedFromWords(MNEMONIC), r.index); } catch (e) { code = e.code; }
  if (code !== r.error) throw new Error(`refusal ${r.id}: ${code}`);
}
mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, 'bip85.json'), JSON.stringify({
  note: 'Generated by clients/clientkeys/scripts/keys-vectors.mjs (scaas-sdk plan T5) from src/seed.js bip85Child; never edit by '
    + 'hand. children: BIP-85 BIP-39 24-word children m/83696968\'/39\'/0\'/24\'/<index>\' of the repository mnemonic\'s seed with '
    + 'the BIP-39 passphrase given (the SDK derives from the main set only; the hidden rows show another parent gives other '
    + 'children). manifests: ua-rs\'s manifest JSON with bip85Next, written only when non-zero, last.',
  mnemonic: MNEMONIC,
  children,
  manifests,
  refusals,
}, null, 1) + '\n');
console.log(`keys vectors: ${children.length} children, ${manifests.length} manifests -> ${OUT}`);
