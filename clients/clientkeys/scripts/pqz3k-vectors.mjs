// Generates smartcontracts/vectors/ua/pqz3k_kat.json: the client rows of the PQZ three-key model a wallet needs besides
// pq_kat.json's seeds (Fable review of the round, P2-2; spec 2026-11-13 pqz-three-keys K3-2, K3-3, CTR-PQZ-40, CTR-PQZ-41):
//   handles          the key handle's seed commitment keccak256(seed32) and opening KEM key hash per class and version;
//   ownTagOpening    ownTag over P(u_f) ‖ P(v_f) of an opening token's op 1, class 2 and class 3;
//   entries          h(i) of a credit, a skip-marked credit and a TRIVIAL entry, and one entriesHash;
//   scopedKeyRecords the UAPqzScopedKey / UAPqzScopedKeyRecord digests and both messages, class 2 and 3, with and without openKem;
//   openingBlob      one opening op 1 blob with the auditor (n = 2) at n2304-kmax4096 and its field offsets.
// The scoped seeds are derived here independently of the library (the handle keeps them); forge checks the record digests
// and h(i) against UAKinds / the token's encoding (test/pqz/PqzClientRows.t.sol), ua-rs and clientkeys read every row.
//   node scripts/pqz3k-vectors.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { hkdf } from "@noble/hashes/hkdf.js";
import { sha256 } from "@noble/hashes/sha2.js";
import { seedFromWords } from "../src/seed.js";
import { hex, keccak_256, utf8ToBytes, concatBytes } from "../src/bytes.js";
import { pqzOwnTag } from "../src/evm.js";
import {
  pqzKeyHandle,
  pqzLayout,
  pqzEntryHash,
  pqzEntriesHash,
  pqzScopedKeyMessages,
  SKIP,
  OPENING,
} from "../src/pqzopen.js";

const M =
  "bench hurt jump file august wise shallow faculty impulse spring exact slush thunder author " +
  "capable act festival slice deposit sauce coconut afford frown better";
const seed = seedFromWords(M);
const kat = (s) => keccak_256(utf8ToBytes(`scaas three-keys kat ${s}`));
const bytesOf = (label, n) =>
  concatBytes(...Array.from({ length: Math.ceil(n / 32) }, (_, j) => kat(`${label} ${j}`))).subarray(0, n);
const be = (n, v) => {
  const b = new Uint8Array(n);
  let x = BigInt(v);
  for (let i = n - 1; i >= 0; i--) {
    b[i] = Number(x & 0xffn);
    x >>= 8n;
  }
  return b;
};
const unhex = (h) => Uint8Array.from(Buffer.from(h.slice(2), "hex"));
const SET = { name: "n2304-kmax4096", n: 2304, packBits: 46 };
const L = pqzLayout(SET.n, SET.packBits);
const CHAIN = hex(kat("chain A"));
const TOKEN = "0x5ca00000000000000000000000000000000000a3";
const ZERO20 = "0x" + "00".repeat(20);
const UA = hex(kat("holder ua"));
const scopedSeed = (token, version) =>
  hkdf(
    sha256,
    seed,
    utf8ToBytes("scaas.ua.pq.v1"),
    concatBytes(
      utf8ToBytes(token === undefined ? "scaas.ua.pqz-mlwe.offchain-shared.v1" : "scaas.ua.pqz-mlwe.offchain-token.v1"),
      be(4, 0),
      be(4, 0),
      unhex(CHAIN),
      token === undefined ? new Uint8Array(0) : unhex(token),
      be(8, version),
    ),
    32,
  );

const out = {
  note:
    "Generated by clients/clientkeys/scripts/pqz3k-vectors.mjs (Fable P2-2). Account 0, index 0 of the mnemonic; set layout " +
    `${SET.name} (P(u) ${L.pkp} B, P(v) ${L.vp} B).`,
  mnemonic: M,
  account: 0,
  index: 0,
  set: SET,
  layout: L,
  chainUid: CHAIN,
  ua: UA,
};

out.handles = [undefined, TOKEN].flatMap((token) =>
  [0, 1].map((version) => {
    const h = pqzKeyHandle(seed, { chainUid: CHAIN, token, ua: UA, version, layout: L });
    const r = {
      keyClass: token === undefined ? "offchain-shared" : "offchain-token",
      ...(token ? { token } : {}),
      version,
      seedCommitment: hex(keccak_256(scopedSeed(token, version))),
      openKemHash: hex(keccak_256(h.openKem)),
    };
    if (h.seedCommitment() !== r.seedCommitment) throw new Error("the handle and the generator derive different seeds");
    h.wipe();
    return r;
  }),
);

const puf = bytesOf("u_f", L.pkp);
const pvf = bytesOf("v_f", L.vp);
out.ownTagOpening = [undefined, TOKEN].map((token) => {
  const t = pqzOwnTag({
    seed32: scopedSeed(token, 0),
    chainUid: CHAIN,
    token: token ?? TOKEN,
    fromUA: UA,
    sendCounter: 5,
    pu: puf,
    pvf,
  });
  t.key.fill(0);
  return {
    keyClass: token === undefined ? "offchain-shared" : "offchain-token",
    token: token ?? TOKEN,
    version: 0,
    sendCounter: 5,
    puf: hex(puf),
    pvf: hex(pvf),
    ownTag: t.ownTag,
  };
});

const slot = (blob, len, block) =>
  "0x" + ((BigInt(blob) << 96n) | (16n << 80n) | (BigInt(len) << 64n) | BigInt(block)).toString(16).padStart(64, "0");
const code = concatBytes(Uint8Array.of(0), bytesOf("entry blob", 200));
const credit = slot("0x5eed0000000000000000000000000000000000a1", 200, 7);
const marked = "0x" + (BigInt(credit) | SKIP).toString(16).padStart(64, "0");
const trivial = "0x" + ((100n << 96n) | 9n).toString(16).padStart(64, "0"); // amount in the address field, length 0
out.entries = {
  code: hex(code),
  rows: [
    { what: "credit", index: 3, slot: credit, code: true },
    { what: "credit, skip-marked (h(i) hashes the slot with the mark cleared)", index: 4, slot: marked, code: true },
    { what: "TRIVIAL", index: 5, slot: trivial, code: false },
  ].map((r) => ({ ...r, h: hex(pqzEntryHash(r.index, r.slot, r.code ? code : undefined)) })),
};
out.entries.entriesHash = hex(pqzEntriesHash(out.entries.rows.map((r) => unhex(r.h))));

const pqzKeyHash = hex(kat("pqz key hash"));
const pqzPopHash = hex(kat("pqz pop hash"));
const openKemHash = hex(kat("open kem hash"));
out.scopedKeyRecords = [
  [2, ZERO20, openKemHash],
  [3, TOKEN, openKemHash],
  [3, TOKEN, "0x" + "00".repeat(32)],
].map(([keyClass, token, okh]) => {
  const r = {
    ua: UA,
    keyClass,
    chainUid: CHAIN,
    token,
    version: 1,
    pqzKeyHash,
    pqzPopHash,
    openKemHash: okh,
    validUntilBlock: 123456,
  };
  const m = pqzScopedKeyMessages(0x0131, r);
  return {
    kind: 0x0131,
    ...r,
    keyDigest: hex(m.keyDigest),
    recordDigest: hex(m.recordDigest),
    message: hex(m.message),
    regMessage: hex(m.regMessage),
  };
});

const parts = [
  ["salt", 16],
  ["pu", L.pkp],
  ["pvt", L.vp],
  ["pva", L.vp],
  ["toUA", 32],
  ["puf", L.pkp],
  ["pvf", L.vp],
  ["oT", OPENING],
  ["oA", OPENING],
  ["ownTag", 32],
];
const at = {};
let p = 0;
const pieces = parts.map(([name, n]) => {
  at[name] = p;
  p += n;
  return name === "toUA" ? unhex(UA) : bytesOf(`blob ${name}`, n);
});
at.kv = p;
const data = concatBytes(...pieces, be(8, 0), be(8, 2), Uint8Array.of(2));
out.openingBlob = { n: 2, kv: [0, 2], code: hex(concatBytes(Uint8Array.of(0), data)), at, dataLen: data.length };

const path = new URL("../../../smartcontracts/vectors/ua/pqz3k_kat.json", import.meta.url);
const text = JSON.stringify(out, null, 1) + "\n";
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== text) {
    console.error("pqz3k-vectors.mjs --check: smartcontracts/vectors/ua/pqz3k_kat.json differs");
    process.exit(1);
  }
  console.log("pqz3k-vectors.mjs --check: ok");
} else {
  writeFileSync(path, text);
  console.log("wrote smartcontracts/vectors/ua/pqz3k_kat.json");
}
