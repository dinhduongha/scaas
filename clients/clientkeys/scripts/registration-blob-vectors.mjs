// Generates smartcontracts/vectors/ua/registration_blobs.json (scaas-sdk spec §7.1, R16; plan T13b): one valid sponsored
// registration blob per single-key signing kind of ua/portable.json (`register`, `registerWebAuthn`), built by src/ua.js
// registrationBlob from the row's inputs; a KEM holder's row twice, the full key (`kem` null) and the hash commit (`kem` set).
// Each full blob's `args` equals the row's `args` (checked before writing).
//   node scripts/registration-blob-vectors.mjs [outDir]
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { registrationBlob } from "../src/ua.js";

const VEC = fileURLToPath(new URL("../../../smartcontracts/vectors/ua/", import.meta.url));
const OUT = process.argv[2] ?? VEC;

export function blobRows() {
  const portable = JSON.parse(readFileSync(join(VEC, "portable.json")));
  const rows = [];
  for (const r of portable.registrations) {
    if (!["register", "registerWebAuthn"].includes(r.args.entry)) continue;
    const input = {
      kind: r.kind,
      keyData: r.keyData,
      pqzKey: r.attrs.pqzKey,
      pqzPop: r.args.pqzPop,
      kemPk: r.attrs.kemPk,
      pop: r.args.pop,
    };
    const full = registrationBlob({ ...input, kemCommit: false });
    if (JSON.stringify(full.args) !== JSON.stringify(r.args) || full.ua !== r.ua) throw new Error(`${r.name}: not the row's`);
    rows.push({ name: r.name, blob: full });
    if (r.attrs.kemPk !== "0x") rows.push({ name: `${r.name}/kem-commit`, blob: registrationBlob({ ...input, kemCommit: true }) });
  }
  return rows;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = {
    note: "Generated by clients/clientkeys/scripts/registration-blob-vectors.mjs (src/ua.js registrationBlob) from ua/portable.json. Do not edit.",
    version: 1,
    blobs: blobRows(),
  };
  writeFileSync(join(OUT, "registration_blobs.json"), JSON.stringify(out, null, 1) + "\n");
  console.log(`registration_blobs.json: ${out.blobs.length} blobs`);
}
