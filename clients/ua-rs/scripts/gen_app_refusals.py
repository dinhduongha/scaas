"""Generates clients/ua-rs/src/wallet/app_refusals.rs (scaas-sdk spec §12.4, plan T21): the lists `sign_app_record` refuses,
from smartcontracts/evm/src/: every SCaaS purpose constant of src/ua/UAKinds.sol (`PURPOSE_*`, `APP_PURPOSE_NS`) with its
string, and every EIP-712 domain name "SCaaS ..." written in the contracts (code or NatSpec: a superset is the safe side).
Each purpose string must be ASCII `scaas.ua.purpose.*` shorter than 64 bytes (review r2 R14).
  python3 clients/ua-rs/scripts/gen_app_refusals.py [--check]"""

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / "smartcontracts/evm/src"
OUT = ROOT / "clients/ua-rs/src/wallet/app_refusals.rs"
PURPOSE = re.compile(r'bytes32 internal constant ((?:PURPOSE_[A-Z0-9_]+)|APP_PURPOSE_NS)\s*=\s*keccak256\("([^"]+)"\)')
NAME = re.compile(r'"(SCaaS [A-Za-z0-9 ]+)"')


def lists():
    purposes = PURPOSE.findall((SRC / "ua/UAKinds.sol").read_text())
    for name, s in purposes:
        if not (s.isascii() and s.startswith("scaas.ua.purpose.") and len(s) < 64):
            sys.exit(f"purpose {name}: {s!r} is not an ASCII scaas.ua.purpose.* string under 64 bytes")
    names = set()
    for f in sorted(SRC.rglob("*.sol")):
        if "legacy" in f.parts:
            continue
        names.update(n.strip() for n in NAME.findall(f.read_text()))
    return purposes, sorted(names)


def render():
    purposes, names = lists()
    out = [
        "// SPDX-License-Identifier: LicenseRef-Vegan-Community-1.0",
        "//! Generated by clients/ua-rs/scripts/gen_app_refusals.py from smartcontracts/evm/src/; never edit by hand. The SCaaS",
        "//! purposes and EIP-712 domain names `sign_app_record` refuses (scaas-sdk spec §12.4).",
        "",
        "/// Every SCaaS purpose constant of `UAKinds.sol` (`APP_PURPOSE_NS` included): its name and its string.",
        "pub const SCAAS_PURPOSES: &[(&str, &str)] = &[",
        *[f'    ("{n}", "{s}"),' for n, s in purposes],
        "];",
        "",
        '/// Every EIP-712 domain name "SCaaS ..." the contracts write.',
        "pub const SCAAS_DOMAIN_NAMES: &[&str] = &[",
        *[f'    "{n}",' for n in names],
        "];",
        "",
    ]
    return "\n".join(out)


def formatted(text):
    """`text` as rustfmt (the crate's toolchain, edition 2021) writes it, so `cargo fmt` leaves the file alone."""
    p = subprocess.run(
        ["rustfmt", "--edition", "2021"], input=text, capture_output=True, text=True, cwd=ROOT / "clients/ua-rs"
    )
    if p.returncode != 0:
        sys.exit(f"rustfmt failed: {p.stderr}")
    return p.stdout


if __name__ == "__main__":
    text = formatted(render())
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is stale: run clients/ua-rs/scripts/gen_app_refusals.py")
        print("app refusals in sync")
    else:
        OUT.write_text(text)
        print(f"wrote {OUT.relative_to(ROOT)}")
