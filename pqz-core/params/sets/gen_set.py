#!/usr/bin/env python3
"""PQZL parameter sets (owner 2026-10-21: one directory per set, chosen at compile time, one set per library build):
every parameter-dependent constant of the C and Rust cores outside LaZer's codegen headers, written as
sets/<set>/pqz_set.h (C) and sets/<set>/rust/set.rs (Rust) from (n, K_MAX, q) by the budget of
pqz-core/pqzl/params/n-study/budget.py (norm bounds, digit / carry / noise widths, Delta) and the ring constants (NTT roots,
Barrett constants). Stdlib only, deterministic:
  python3 -I pqz-core/params/sets/gen_set.py           write every set
  python3 -I pqz-core/params/sets/gen_set.py --check   exit 1 if a committed file differs
Sets (named by n and K_MAX, owner 2026-10-21): n2048-kmax1024 = the frozen v3 set (n 2048, q = 2^42 - 215, K_MAX 1,024: main's build, its vectors and KATs reproduce);
n2304-kmax4096 = set (a) (owner 2026-10-21; n 2304, q = 61,275,424,977,257, K_MAX 4,096; plan 5h Task 8b).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "pqzl", "params", "n-study"))
from budget import budget  # noqa: E402

SETS = {"n2048-kmax1024": (2048, 1024, 2**42 - 215, "the frozen v3 set (proofSystemId .../mlwe-d64k32-q42l4/v3)"),
        "n2304-kmax4096": (2304, 4096, 61_275_424_977_257, "set (a), owner 2026-10-21 (plan 5h Task 8b)")}


def consts(name):
    n, K, q, what = SETS[name]
    b = budget(n, K, q)
    assert b["ok"] and q % 16 == 9
    L = (q - 1).bit_length()                  # the ring's log2q (LaZer codegen: ceil(log2(q - 1)))
    assert 2**(L - 1) < q < 2**L
    g = 3
    z = pow(g, (q - 1) // 8, q)
    assert pow(z, 4, q) == q - 1               # primitive 8th root: zeta = 3^((q - 1) / 8) for both sets
    i, z3 = z * z % q, pow(z, 3, q)
    inv = lambda x: pow(x, q - 2, q)  # noqa: E731
    mbits, ebits = b["m"], b["e_bits"] + 1
    assert 2 * L + 4 <= L + 63           # Barrett: floor(x / 2^(L-1)) MUX < 2^128
    # pqz_sv.c's largest sum: c (sum over <= 65 products of two values < q, 64 terms each), 2^9 for c: < 2^(2L + 22);
    # NP primes near 2^30 hold |x| < P / 2 ~ 2^(30 NP - 1)
    sv_np = next(m for m in range(4, 8) if 30 * m - 1 > 2 * L + 22 + 1)
    c = [("SET_NAME", None, f'"{name}"', "the set's name"),
         ("K", b["k"], None, "polys per key / ciphertext vector u"), ("N", n, None, "ring dimension n = k d"),
         ("Q", q, None, "the modulus (prime, q = 9 mod 16)"), ("LOG2Q", L, None, "ceil(log2(q - 1)): coder / urandom width of a value mod q, A expansion"),
         ("DELTA", b["D"], None, f"floor(q / 2^{mbits + 2})"), ("K_MAX", K, None, "credits per account between refreshes"),
         ("MBITS", mbits, None, "digit sums M_i < 2^MBITS (15 K_MAX < 2^MBITS)"),
         ("CBITS", mbits - 3, None, "carries c_i + 64, i < 15"),
         ("EBITS", ebits, None, f"e_T,i + 2^{ebits - 1} and e'_i + 2^{ebits - 1} (|e| < E = 2^{ebits - 1})"),
         ("BETA_S", b["bs"], None, "||s||, ||r|| bound (CBD(1))"), ("BETA_E", b["be"], None, "||e||, ||e1|| bound (CBD(20))"),
         ("BETA_2", 64, None, "||e2_j|| bound (16 coefficients)"),
         ("ZETA", z, None, "3^((q - 1) / 8), a primitive 8th root of unity"), ("IROOT", i, None, "zeta^2"),
         ("ZETA3", z3, None, "zeta^3"), ("INV2", inv(2), None, "1/2"), ("INVZ", inv(z), None, "1/zeta"),
         ("INVI", inv(i), None, "1/zeta^2"), ("INVZ3", inv(z3), None, "1/zeta^3"),
         ("R64", 2**64 % q, None, "2^64 mod q"),
         ("BARX", 2 * L + 4, None, "Barrett input range: x < 2^BARX = 2^(2 log2q + 4) > 16 q^2 (a basemul column sum)"),
         ("MUX", 2**(2 * L + 4) // q, None, "floor(2^BARX / q) < 2^(log2q + 5)"),
         ("SV_NP", sv_np, None, "30-bit CRT primes of the specialised verifier (pqz_sv.c): P / 2 above its largest sum")]
    return n, K, q, what, c


def c_text(name):
    n, K, q, what, cs = consts(name)
    out = [f"/* PQZL parameter set {name}: {what}. Generated by pqz-core/params/sets/gen_set.py: do not edit.",
           "   One set per library build (pqzl/build.sh PQZ_SET=<set>: pqz-core/params/sets/<set>). */",
           "#ifndef PQZ_SET_H", "#define PQZ_SET_H", ""]
    for k, v, s, doc in cs:
        val = s if s is not None else (f"{v}ULL" if k in ("Q", "ZETA", "IROOT", "ZETA3", "INV2", "INVZ", "INVI", "INVZ3", "R64", "MUX") else
                                      f"((int64_t){v})" if k == "DELTA" else str(v))
        out.append(f"#define PQZ_{k} {val} /* {doc} */")
    out += ["", "#endif", ""]
    return "\n".join(out)


def rs_text(name):
    n, K, q, what, cs = consts(name)
    out = [f"//! PQZL parameter set `{name}`: {what}. Generated by `pqz-core/params/sets/gen_set.py`: do not edit.",
           "//! One set per build (cargo features `set-n2304-kmax4096` / `set-n2048-kmax1024`); `crate::params::set` re-exports it.",
           "#![allow(dead_code)]"]
    for k, v, s, doc in cs:
        if s is not None:
            out.append(f"/// {doc}\npub(crate) const {k}: &str = {s};")
            continue
        ty = "u64" if k in ("Q", "ZETA", "IROOT", "ZETA3", "INV2", "INVZ", "INVI", "INVZ3", "R64", "MUX") else \
             "i64" if k == "DELTA" else "u32" if k in ("LOG2Q", "MBITS", "CBITS", "EBITS", "BARX") else "usize"
        out.append(f"/// {doc}\npub(crate) const {k}: {ty} = {v:_};")
    out.append("")
    return "\n".join(out)


def files():
    return {os.path.join(HERE, s, "pqz_set.h"): c_text(s) for s in SETS} | \
           {os.path.join(HERE, s, "rust", "set.rs"): rs_text(s) for s in SETS}


def main():
    check = sys.argv[1:] == ["--check"]
    bad = []
    for p, t in files().items():
        if check:
            if not os.path.exists(p) or open(p, encoding="ascii").read() != t:
                bad.append(os.path.relpath(p, HERE))
        else:
            with open(p, "w", encoding="ascii", newline="\n") as f:
                f.write(t)
    print("gen_set.py%s: %d files%s" % (" --check" if check else "", len(files()), (", differ: " + " ".join(bad)) if bad else ""))
    return 1 if bad else 0


if __name__ == "__main__":
    # self-check: the v3 set is today's frozen constants (pqz_ntt.c / pqz_rel.c / pqz_keys.c of main)
    c = {k: v for k, v, s, d in consts("n2048-kmax1024")[4]}
    assert (c["K"], c["Q"], c["LOG2Q"], c["DELTA"], c["MBITS"], c["CBITS"], c["EBITS"]) == (32, 4398046510889, 42, 2**26 - 1, 14, 11, 25)
    assert (c["BETA_S"], c["BETA_E"], c["ZETA"], c["INVZ3"]) == (36, 164, 3367489746414, 1030556764475)
    c = {k: v for k, v, s, d in consts("n2304-kmax4096")[4]}
    assert (c["K"], c["DELTA"], c["MBITS"], c["EBITS"], c["BETA_S"], c["BETA_E"]) == (36, 233747196, 16, 27, 38, 173)
    sys.exit(main())
