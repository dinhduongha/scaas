"""D8: the generated LaZer parameter headers of each parameter set, pqz-core/params/sets/<set>/pqz_*_params.h ->
pqz-core/params/sets/<set>/rust/<rel>.rs (+ that set's mod.rs, which also declares its set.rs of gen_set.py), and the crate's
pqzl/rust/src/params/mod.rs (the structs; one set chosen by the cargo feature set-<set>, owner 2026-10-21).

  python3 -I pqz-core/pqzl/params/to_rust.py [set ...]  write the .rs files (default: every set)
  python3 -I pqz-core/pqzl/params/to_rust.py --check    exit 1 if a committed .rs file differs from the regenerated text

Stdlib only, deterministic. Each header's statements become typed Rust items with the C names lower-cased
(`pqz_tx_Bsq` -> `pqz_tx_bsq`); the struct initializers are positional in C, so they are mapped onto the fields of
lazer-in2.h's structs by the tables below (tests/oracle_params.rs reads every field back through the C compiler).
The parser is strict: a statement it does not know fails, so a codegen change cannot slip through silently.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "rust", "src", "params")
SETS_DIR = os.path.join(HERE, "..", "..", "params", "sets")
DEFAULT_SET = "n2304-kmax4096"  # the crate's default feature (Cargo.toml)


def sets():
    return sorted(d for d in os.listdir(SETS_DIR) if os.path.exists(os.path.join(SETS_DIR, d, "pqz_set.h")))
OVERSIZE = {"txm16", "txm160"}  # pqz_rel.c includes them only under PQZ_TXM_OVERSIZE

# lazer-in2.h's structs, field by field: (Rust field, kind)
