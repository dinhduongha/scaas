def fail(hdr, msg):
    raise SystemExit("to_rust.py: %s: %s" % (hdr, msg))


def num(hdr, s, kind):
    m = re.fullmatch(r"(-?\d+)U?L?", s)
    if not m:
        fail(hdr, "not an integer: %r" % s)
    v = int(m.group(1))
    lo, hi = RANGE[kind]
    if not lo <= v <= hi:
        fail(hdr, "%s out of range for %s" % (s, kind))
    return v


def convert(hdr, text):
    """header text -> the module's Rust text"""
    doc, items = [], []
    limbs, ints, u32s, intarrs, structs = {}, {}, {}, {}, {}  # C name -> data / kind

    def ref(name, table):
        if name not in table:
            fail(hdr, "undefined %s" % name)
        return name.lower()

    for line in text.splitlines():
        if line.startswith("//"):
            doc.append(line[2:].rstrip())
            continue
        if not line.strip() or line == '#include "lazer.h"':
            continue
        m = re.fullmatch(r"static const (limb_t|int_t|unsigned int|int_srcptr|\w+_t) (\w+)(\[\d*\])? = \{(.*)\};", line)
        if not m:
            fail(hdr, "unknown statement: %s" % line)
        ctype, name, dim, init = m.groups()
        rname = name.lower()
        args = [a.strip() for a in init.strip("{} ").split(",")]
        if ctype == "limb_t":
            limbs[name] = [num(hdr, a, "u64") for a in args]
        elif ctype == "int_t":
            mm = re.fullmatch(r"\(limb_t \*\)(\w+)", args[0])
            if not mm or len(args) != 3 or mm.group(1) not in limbs:
                fail(hdr, line)
            l, n, neg = limbs[mm.group(1)], num(hdr, args[1], "u32"), num(hdr, args[2], "bool")
            if n != len(l):
                fail(hdr, "%s: nlimbs %d != %d limbs" % (name, n, len(l)))
            ints[name] = 1
            items.append("pub(crate) const %s: Int = Int::from_limbs(&[%s], %d);" % (rname, ", ".join(map(str, l)), neg))
        elif ctype == "unsigned int":
            v = [num(hdr, a, "u32") for a in args]
            if dim != "[%d]" % len(v):
                fail(hdr, line)
            u32s[name] = len(v)
            items.append("pub(crate) const %s: [u32; %d] = [%s];" % (rname, len(v), ", ".join(map(str, v))))
        elif ctype == "int_srcptr":
            if dim != "[]":
                fail(hdr, line)
            intarrs[name] = len(args)
            items.append("pub(crate) const %s: [Int; %d] = [%s];" % (rname, len(args), ", ".join(ref(a, ints) for a in args)))
        elif ctype in STRUCTS and dim is None:
            rtype, fields = STRUCTS[ctype]
            if len(args) != len(fields):
                fail(hdr, "%s: %d initializers for %d fields" % (name, len(args), len(fields)))
            vals = {}
            out = []
            for (f, kind), a in zip(fields, args):
                if kind == "int":
                    v = ref(a, ints)
                elif kind == "ref":
                    v = "&" + ref(a, structs)
                elif kind == "moduli":
                    if a != "moduli_d64":
                        fail(hdr, "%s: moduli %s" % (name, a))
                    continue
                elif kind in ("ints", "ints0", "u32s"):
                    if kind == "ints0":  # &l2Bsq[0]
                        mm = re.fullmatch(r"&(\w+)\[0\]", a)
                        if not mm:
                            fail(hdr, "%s.%s: %s" % (name, f, a))
                        a = mm.group(1)
                    table = u32s if kind == "u32s" else intarrs
                    v = "&" + ref(a, table)
                    vals[f] = table[a]
                elif kind == "bool":
                    v = "true" if num(hdr, a, kind) else "false"
                else:
                    vals[f] = num(hdr, a, kind)
                    v = str(vals[f])
                out.append("    %s: %s," % (f, v))
            # the array lengths C leaves implicit
            if rtype == "Ring" and vals["ppmodq"] != vals["nmoduli"]:
                fail(hdr, "%s: Ppmodq has %d entries, nmoduli %d" % (name, vals["ppmodq"], vals["nmoduli"]))
            if rtype == "Tbox" and not vals["n"] == vals["l2bsqr"] == vals["z"]:
                fail(hdr, "%s: n / l2Bsqr / Z lengths %d / %d / %d" % (name, vals["n"], vals["l2bsqr"], vals["z"]))
            structs[name] = 1
            items.append("pub(crate) static %s: %s = %s {\n%s\n};" % (rname, rtype, rtype, "\n".join(out)))
        else:
            fail(hdr, "unknown statement: %s" % line)

    while doc and not doc[-1].strip():
        doc.pop()
    head = ["//! Generated by `pqzl/params/to_rust.py` from `pqz-core/params/sets/%s`: do not edit. The header's codegen notes:" % hdr,
            "//!", "//! ```text"] + [("//!" + d).rstrip() for d in doc] + ["//! ```",
            "use super::{Abdlop, Dcomp, Int, QuadEval, Ring, Tbox};", ""]
    return "\n".join(head + items) + "\n"


def generate():
    """{path: text} of every set's modules and mod.rs, and the crate's mod.rs"""
    files = {}
    for st in sets():
        d = os.path.join(SETS_DIR, st)
        rels = sorted(re.fullmatch(r"pqz_(\w+)_params\.h", f).group(1) for f in os.listdir(d)
                      if re.fullmatch(r"pqz_\w+_params\.h", f))
        mods = []
        for r in rels:
            hdr = "pqz_%s_params.h" % r
            with open(os.path.join(d, hdr), encoding="ascii") as f:
                files[os.path.join(d, "rust", r + ".rs")] = convert("%s/%s" % (st, hdr), f.read())
            mods.append(('#[cfg(feature = "oversize")]\n' if r in OVERSIZE else "") + "pub(crate) mod %s;" % r)
        files[os.path.join(d, "rust", "mod.rs")] = (
            "//! Parameter set `%s`: the relations' parameters (generated by `pqzl/params/to_rust.py`, do not edit) and\n"
            "//! `set` (`pqz-core/params/sets/gen_set.py`). Loaded by `pqzl/rust/src/params/mod.rs` under the feature `set-%s`.\n"
            "#![allow(non_upper_case_globals)]\npub(crate) use super::{Abdlop, Dcomp, Int, QuadEval, Ring, Tbox};\n\n"
            "pub(crate) mod set;\n" % (st, st)) + "\n".join(mods) + "\n"
    sel = []
    for st in sets():
        sel.append('#[cfg(feature = "set-%s")]\n#[path = "../../../../params/sets/%s/rust/mod.rs"]\nmod chosen;' % (st, st))
    one = " as u8 + ".join('cfg!(feature = "set-%s")' % st for st in sets())
    files[os.path.join(OUT, "mod.rs")] = (MOD_RS + "\n// exactly one parameter set per build\nconst _: () = assert!(" + one +
                                          ' as u8 == 1, "enable exactly one set-<set> feature");\n' + "\n".join(sel) +
                                          "\npub(crate) use chosen::*;\n")
    return files


def main():
    args = sys.argv[1:]
    check = args == ["--check"]
    if not check and any(a not in sets() for a in args):
        raise SystemExit(__doc__)
    files = generate()
    if check:
        have = set()
        for d in [OUT] + [os.path.join(SETS_DIR, st, "rust") for st in sets()]:
            if os.path.isdir(d):
                have |= {os.path.join(d, f) for f in os.listdir(d) if f.endswith(".rs") and f != "set.rs"}
        bad = sorted(os.path.relpath(p, HERE) for p in have ^ set(files))
        for p in sorted(set(files) & have):
            with open(p, encoding="ascii") as fh:
                if fh.read() != files[p]:
                    bad.append(os.path.relpath(p, HERE))
        print("to_rust.py --check: %d files, %s" % (len(files), "differ: " + " ".join(bad) if bad else "equal"))
        return 1 if bad else 0
    want = args or sets()
    n = 0
    for p, t in files.items():
        if p.startswith(OUT) or any(p.startswith(os.path.join(SETS_DIR, st) + os.sep) for st in want):
            os.makedirs(os.path.dirname(p), exist_ok=True)
            with open(p, "w", encoding="ascii", newline="\n") as fh:
                fh.write(t)
            n += 1
    print("to_rust.py: wrote %d files (sets %s)" % (n, " ".join(want)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
