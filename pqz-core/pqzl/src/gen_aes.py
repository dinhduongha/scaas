#!/usr/bin/env python3
"""Generate pqz_aes_gen.h: the fixed bit permutations and the GF(2^8) squaring map of the bitsliced AES.

Layout (pqz_aes.c): 64 bytes = 4 AES blocks; byte j = 16 * block + pos, pos = 4 * column + row (FIPS-197 input
order). Bit plane p (uint64) holds bit p of every byte, byte j in bit j. ShiftRows and the MixColumns row rotations
are the same bit permutation on every plane; each is emitted as a sum of masked shifts.
Run: python3 gen_aes.py > pqz_aes_gen.h
"""


def perm_code(name, src_of):
    """src_of[dst] = src bit index; emit out = OR over shifts of ((x >> s) & mask) / ((x << s) & mask)."""
    groups = {}
    for dst in range(64):
        groups.setdefault(src_of[dst] - dst, 0)
        groups[src_of[dst] - dst] |= 1 << dst
    terms = []
    for delta, mask in sorted(groups.items()):
        if delta > 0:
            terms.append(f"((x >> {delta}) & 0x{mask:016x}ULL)")
        elif delta < 0:
            terms.append(f"((x << {-delta}) & 0x{mask:016x}ULL)")
        else:
            terms.append(f"(x & 0x{mask:016x}ULL)")
    body = "\n         | ".join(terms)
    return f"static inline uint64_t\n{name} (uint64_t x)\n{{\n  return {body};\n}}\n"


def shiftrows():
    src = [0] * 64
    for blk in range(4):
        for c in range(4):
            for r in range(4):
                src[16 * blk + 4 * c + r] = 16 * blk + 4 * ((c + r) % 4) + r
    return src


def rotrow(k):
    """byte (column c, row r) takes the byte of row (r + k) mod 4 of the same column"""
    src = [0] * 64
    for blk in range(4):
        for c in range(4):
            for r in range(4):
                src[16 * blk + 4 * c + r] = 16 * blk + 4 * c + (r + k) % 4
    return src


def gmul(a, b):
    r = 0
    for _ in range(8):
        if b & 1:
            r ^= a
        hi = a & 0x80
        a = (a << 1) & 0xFF
        if hi:
            a ^= 0x1B
        b >>= 1
    return r


def square_matrix():
    """rows[i] = set of input bits whose XOR is output bit i of x^2"""
    cols = [gmul(1 << j, 1 << j) for j in range(8)]  # squaring is linear: image of each basis bit
    return [[j for j in range(8) if (cols[j] >> i) & 1] for i in range(8)]


out = ["/* generated by gen_aes.py -- do not edit */", "#ifndef PQZ_AES_GEN_H", "#define PQZ_AES_GEN_H", ""]
out.append(perm_code("pqz_aes_shiftrows", shiftrows()))
for k in (1, 2, 3):
    out.append(perm_code(f"pqz_aes_rotrow{k}", rotrow(k)))
rows = square_matrix()
out.append("static inline void\npqz_aes_gfsq (uint64_t r[8], const uint64_t a[8])\n{")
out.append("  uint64_t t[8];")
for i, row in enumerate(rows):
    out.append(f"  t[{i}] = " + " ^ ".join(f"a[{j}]" for j in row) + ";")
out.append("  for (int i = 0; i < 8; i++)\n    r[i] = t[i];\n}\n")
out.append("#endif")
print("\n".join(out))
