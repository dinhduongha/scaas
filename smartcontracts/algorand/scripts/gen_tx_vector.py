"""Algorand transaction vector for scaas-node's hand-encoded canonical msgpack (near-algorand T17): a relay-fee group
`[Payment lane → router] [appl target, sender = executor LogicSig] [appl router.relay by the lane, fee pooled, foreign
arrays and boxes] [bare budget call]` built and signed by py-algorand-sdk 2.12.0. scaas-node's
`adapters::algorand::tests::tx_matches_algosdk` rebuilds the same group and must produce the same bytes.

    python3 -I scripts/gen_tx_vector.py           # check vectors/algorand-tx.json
    python3 -I scripts/gen_tx_vector.py --write   # rewrite it
"""
import base64
import hashlib
import json
import os
import sys

from algosdk import encoding, transaction
from nacl.signing import SigningKey

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'vectors', 'algorand-tx.json')
V = json.load(open(os.path.join(ROOT, 'vectors', 'algorand-vectors.json')))


def h(b):
    return '0x' + b.hex()


def main():
    seed = hashlib.sha256(b'scaas.algorand.tx-vector').digest()
    sk = SigningKey(seed)
    pk = bytes(sk.verify_key)
    lane = encoding.encode_address(pk)
    secret = base64.b64encode(seed + pk).decode()
    gh = bytes.fromhex(V['network'][2:])
    sp = transaction.SuggestedParams(0, 1000, 2000, base64.b64encode(gh).decode(), 'scaas-localnet-v1', flat_fee=True)
    program = bytes.fromhex(V['executor']['program'][2:])
    lsig = transaction.LogicSigAccount(program)
    router, target, token = V['executor']['routerApp'], V['apps']['target']['id'], V['apps']['token']['id']
    alice = V['keys']['alice']['address']
    pay = transaction.PaymentTxn(lane, sp, encoding.encode_address(
        hashlib.new('sha512_256', b'appID' + router.to_bytes(8, 'big')).digest()), 18_900)
    args = [bytes.fromhex(a[2:]) for a in V['routerCall']['args']]
    tgt = transaction.ApplicationCallTxn(lsig.address(), sp, target, transaction.OnComplete.NoOpOC, app_args=args)
    relay_args = [bytes.fromhex('4af7ebf5'), token.to_bytes(8, 'big'), b'\x07' * 291, (3).to_bytes(2, 'big') + b'abc']
    sp_fee = transaction.SuggestedParams(7000, 1000, 2000, sp.gh, sp.gen, flat_fee=True)
    relay = transaction.ApplicationCallTxn(lane, sp_fee, router, transaction.OnComplete.NoOpOC, app_args=relay_args,
                                           accounts=[alice], foreign_apps=[token],
                                           boxes=[(token, b'l' + b'\x01' * 32), (0, b'')])
    budget = transaction.ApplicationCallTxn(lane, sp, token, transaction.OnComplete.NoOpOC,
                                            boxes=[(token, b'u' + b'\x02' * 32)])
    txns = [pay, tgt, relay, budget]
    gid = transaction.calculate_group_id(txns)
    for t in txns:
        t.group = gid
    signed = [pay.sign(secret), transaction.LogicSigTransaction(tgt, lsig), relay.sign(secret), budget.sign(secret)]
    raw = b''.join(base64.b64decode(encoding.msgpack_encode(s)) for s in signed)
    out = {
        'note': 'Generated by smartcontracts/algorand/scripts/gen_tx_vector.py (py-algorand-sdk 2.12.0); never edit by hand',
        'seed': h(seed), 'lane': lane, 'genesisId': sp.gen, 'genesisHash': h(gh), 'firstValid': 1000, 'lastValid': 2000,
        'executorProgram': V['executor']['program'], 'executor': lsig.address(),
        'router': router, 'target': target, 'token': token, 'alice': alice,
        'targetArgs': V['routerCall']['args'], 'relayArgs': [h(a) for a in relay_args], 'relayFee': 7000,
        'mbr': 18_900, 'group': h(gid),
        'txns': [{'unsigned': h(base64.b64decode(encoding.msgpack_encode(t))), 'txid': h(base64.b32decode(t.get_txid() + '===='))
                  , 'signed': h(base64.b64decode(encoding.msgpack_encode(s)))} for t, s in zip(txns, signed)],
        'raw': h(raw),
    }
    text = json.dumps(out, indent=1) + '\n'
    if '--write' in sys.argv:
        open(OUT, 'w').write(text)
        print('wrote', OUT)
    elif open(OUT).read() != text:
        sys.exit('vectors/algorand-tx.json is stale: run gen_tx_vector.py --write')
    else:
        print('ok', OUT)


if __name__ == '__main__':
    main()
