"""Group 3l, plan T102 (wrap limits spec 2026-11-10-wrap-limits.md §2.1, R23, R24, R26): rows of the net-wrapped entitlement's
arithmetic, so a wallet that previews the entitlement between reads matches the contract. Each row: a leg's `unitExp` and
`decayDays`, a start time, then steps (`wrap` raw units received, `unwrap` raw units out, `warp` seconds); after each step the
id's `base` (quanta), `startMin` (absolute minute) and `entitlement` (raw units). Replayed on the contract by
`smartcontracts/evm/test/wrap/WrapLimitsVectors.t.sol`; recomputed by `clientkeys` and `ua-rs`.

usage: python3 gen_wraplimits.py [--check]   (--check: the file equals what this writes)   UNAUDITED tooling."""
import json
import os
import sys

MAX32 = 2**32 - 1
T0 = 1_800_000_000  # a whole minute


def ceil_div(a, b):
    return -(-a // b)


class Id:
    """One id on one leg: `b` quanta, `s` an absolute minute (spec §2.1 in minutes, R26)."""

    def __init__(self, unit_exp, decay_days):
        self.unit, self.h, self.b, self.s = 10 ** unit_exp, decay_days * 1440, 0, 0

    def ent(self, now_min):
        g = max(now_min - self.s, 0)
        if self.h == 0:
            return self.b, g
        g = min(g, self.h)
        return self.b * (self.h - g) // self.h, g

    def wrap(self, x, now_min):
        a = x // self.unit
        if a == 0:
            return
        e, g = self.ent(now_min)
        g2 = ceil_div(e * g, e + a)
        b2 = self.b + a
        if self.h:
            b2 = min(b2, (e + a) * self.h // (self.h - g2))
        self.b, self.s = min(b2, MAX32), now_min - g2

    def unwrap(self, x, now_min):
        q = ceil_div(x, self.unit)
        e, _ = self.ent(now_min)
        assert q <= e, 'the vector holds unwraps the rule allows'
        self.b = 0 if q >= e else self.b * (e - q) // e


DAY = 86_400
ROWS = [
    ('decay-zero-half-full', 0, 730, [('wrap', 1000), ('warp', 365 * DAY), ('unwrap', 500), ('warp', 365 * DAY)]),
    ('dust-then-one-quantum', 2, 730, [('wrap', 100_000), ('warp', 100 * DAY), ('wrap', 50), ('wrap', 100)]),
    ('a-wrap-as-large-as-E-halves-the-age', 2, 730, [('wrap', 100_000), ('warp', 100 * DAY), ('wrap', 86_300)]),
    ('unwrap-drops-E-by-q-or-q-plus-1', 2, 730, [('wrap', 100_000), ('warp', 100 * DAY), ('unwrap', 10_000), ('unwrap', 10_000)]),
    ('weighted-start-without-decay', 0, 0, [('wrap', 1000), ('warp', 200 * DAY), ('wrap', 1000), ('warp', 165 * DAY),
                                            ('unwrap', 1500)]),
    ('small-top-ups-make-the-start-younger', 0, 730, [('wrap', 1_000_000), ('warp', 100 * DAY), ('wrap', 1000), ('wrap', 1000),
                                                     ('wrap', 1000)]),
    ('round-trip-rejuvenates', 0, 730, [('wrap', 1000), ('warp', 365 * DAY), ('wrap', 500), ('unwrap', 500)]),
    ('saturates', 0, 65_535, [('wrap', 2**32 + 7), ('wrap', 5), ('warp', 1000 * DAY)]),
]


def build():
    rows = []
    for name, unit_exp, decay, steps in ROWS:
        i, t, after = Id(unit_exp, decay), T0, []
        for op, v in steps:
            if op == 'warp':
                t += v
            elif op == 'wrap':
                i.wrap(v, t // 60)
            else:
                i.unwrap(v, t // 60)
            e, _ = i.ent(t // 60)
            after.append({'time': t, 'base': i.b, 'startMin': i.s, 'entitlement': str(e * i.unit)})
        rows.append({'name': name, 'unitExp': unit_exp, 'decayDays': decay, 't0': T0,
                     'steps': [{'op': op, 'value': str(v)} for op, v in steps], 'after': after})
    return {'note': 'Generated by smartcontracts/vectors/wraplimits/gen_wraplimits.py; never edit by hand. Wrap limits spec '
                    '2026-11-10 §2.1 (R23, R24, R26): base in quanta of 10^unitExp raw units, startMin an absolute minute, '
                    'entitlement in raw units, decayDays * 1440 minutes the horizon (0: off). UNAUDITED.',
            'version': 1, 'rows': rows}


def main():
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'wraplimits.json')
    text = json.dumps(build(), indent=1) + '\n'
    if '--check' in sys.argv:
        if open(out).read() != text:
            sys.exit('wraplimits.json is stale: python3 gen_wraplimits.py')
        print('wraplimits.json: equal')
        return
    open(out, 'w').write(text)


if __name__ == '__main__':
    main()
