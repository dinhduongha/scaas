def gen():
    s = open(os.path.join(EVM, "script/ZetherE2E.s.sol")).read()
    for old, new, n in SUBS:
        got = s.count(old)
        assert got and (n is None or got == n), f"ZetherE2E.s.sol changed: {old!r} found {got} times"
        s = s.replace(old, new)
    # the wrapped config: its features line, then the compliance registry (kind 11)
    w = "w.conf) = (\"Zether wrapped E2E USD\""
    i = s.index(w)
    j = s.index("\n", i)
    s = s[:j + 1] + ('        w.reg.complianceRegistry = dep.readAddress(".compliance_registry"); // T66b Step 5b: kind 11, DENYLIST\n'
                     "        (w.features, w.reg.deniedFlags) = (w.features | 1 << GovernanceBits.DENYLIST, 1);\n"
                     '        w.reg.termsHash = keccak256("scaas.onchain.terms");\n') + s[j + 1:]
    os.makedirs(os.path.join(HERE, "build"), exist_ok=True)
    open(os.path.join(HERE, "build/ZetherRegE2E.s.sol"), "w").write(
        "// GENERATED by script/onchain/zether_reg.py from script/ZetherE2E.s.sol (T66b Step 5b): do not edit.\n" + s)
    # ZetherMore's twin: the same entries on ZetherRegE2E's tokens (its `_normal` / `_wrapped` create kinds 10 and 11)
    m = open(os.path.join(HERE, "ZetherMore.s.sol")).read()
    for old, new, n in MORE_SUBS:
        got = m.count(old)
        assert got and (n is None or got == n), f"ZetherMore.s.sol changed: {old!r} found {got} times"
        m = m.replace(old, new)
    open(os.path.join(HERE, "build/ZetherRegMore.s.sol"), "w").write(
        "// GENERATED by script/onchain/zether_reg.py from script/onchain/ZetherMore.s.sol (T66b Step 5b): do not edit.\n" + m)
    print("script/onchain/build/ZetherRegE2E.s.sol script/onchain/build/ZetherRegMore.s.sol")


def book(net, script):
    reg = script in ("ZetherRegE2E", "ZetherRegMore")
    tag = {"ZetherE2E": "zether-e2e", "ZetherRegE2E": "zether-reg-e2e", "ZetherMore": "zether-more",
           "ZetherRegMore": "zether-reg-more"}[script]
    chain, g = os.environ["CHAIN"], os.environ["GENESIS"]  # the target chain (zether.sh): its own deploy and e2e books
    e = deploybook.load(deploybook.find(chain, g, f"-{tag}.json"))
    d = deploybook.load(deploybook.find(chain, g))
    b = {e["normal_zether_token"]: "NormalZetherRegulatedToken" if reg else "NormalZetherToken",
         e["wrapped_zether_token"]: "WrappedZetherRegulatedToken" if reg else "WrappedZetherToken",
         e["underlying_erc20"]: "MockERC20", d["zether_registry"]: "UARegistry", d["token_factory"]: "OpenFactory",
         d["zether_disclosure"]: "ZetherDisclosure"}
    with open(os.path.join(EVM, f"deployments/onchain-{net}-{script.lower()}.json"), "w") as f:
        json.dump(b, f, indent=1)


