"""Variant A's floor: a contract with a kind's whole external ABI (same selectors, same argument and return types), each
entry a stub that only forwards its calldata by DELEGATECALL (no local body, no re-encoding). Its size is the least a token
can be while it keeps every entry point (owner's variant A, 2026-10-21), whatever moves into libraries.

usage: gen_floor.py <forge out dir> <outdir> <Kind> [<Kind> ...] [--fallback KEEP_FILE]
  writes <outdir>/Floor<Kind>.sol. With --fallback, only the selectors listed in KEEP_FILE (one signature per line, '#'
  comments) stay as stubs and a `fallback` forwards every other one: the comparison form (a module behind `fallback`).
Stub forms: state-changing entries carry the token's one guard (`_enter`/`_exit` as `MetaTxBase` has them, lever 2); view
and pure entries forward through a function-pointer cast (the registry R2 form), so the ABI keeps its mutability.
UNAUDITED research tooling.
"""
import json, os, sys

def load_abi(out, name):
    for d in os.listdir(out):
        p = os.path.join(out, d, name + '.json')
        if d.endswith('.sol') and os.path.exists(p):
            return json.load(open(p))['abi']
    sys.exit('no artifact for ' + name)


class Gen:
    def __init__(self):
        self.structs = {}   # canonical -> (name, body)
        self.order = []

    def canon(self, p):
        t = p['type']
        if t.startswith('tuple'):
            return '(' + ','.join(self.canon(c) for c in p['components']) + ')' + t[5:]
        return t

    def sol_type(self, p):
        t = p['type']
        if t.startswith('tuple'):
            inner = '(' + ','.join(self.canon(c) for c in p['components']) + ')'
            if inner not in self.structs:
                name = f'S{len(self.structs)}'
                self.structs[inner] = None
                fields = []
                for i, c in enumerate(p['components']):
                    fields.append(f'        {self.sol_type(c)} f{i};')
                self.structs[inner] = (name, '\n'.join(fields))
                self.order.append(inner)
            return self.structs[inner][0] + t[5:]
        return t

    @staticmethod
    def is_ref(p):
        t = p['type']
        return t.startswith('tuple') or t.endswith(']') or t in ('bytes', 'string')

    def params(self, ps, loc):
        out = []
        for p in ps:
            s = self.sol_type(p)
            out.append(f'{s} {loc}' if self.is_ref(p) else s)
        return ', '.join(out)


def main():
    args = sys.argv[1:]
    keep = None
    if '--fallback' in args:
        i = args.index('--fallback')
        keep = {l.split('#')[0].strip() for l in open(args[i + 1]) if l.split('#')[0].strip()}
        del args[i:i + 2]
    out, outdir, kinds = args[0], args[1], args[2:]
    os.makedirs(outdir, exist_ok=True)
    for k in kinds:
        abi = load_abi(out, k)
        g = Gen()
        fns = []
        nfwd = 0
        for f in abi:
            if f['type'] != 'function':
                continue
            sig = f['name'] + '(' + ','.join(g.canon(p) for p in f['inputs']) + ')'
            if keep is not None and sig not in keep:
                nfwd += 1
                continue
            mut = f['stateMutability']
            ins = g.params(f['inputs'], 'calldata')
            rets = g.params(f['outputs'], 'memory')
            ret = f' returns ({rets})' if f['outputs'] else ''
            if mut in ('view', 'pure'):
                body = f'external {mut}{ret} {{ _fwd{mut.capitalize()}(); }}'
            else:
                pay = ' payable' if mut == 'payable' else ''
                body = f'external{pay} guarded{ret} {{ _fwd(); }}'
            fns.append(f'    function {f["name"]}({ins}) {body} // {sig}')
        structs = '\n'.join(f'    struct {g.structs[c][0]} {{\n{g.structs[c][1]}\n    }}' for c in g.order)
        fb = '\n    fallback() external { _fwd(); }\n' if keep is not None else ''
        name = ('Fb' if keep is not None else 'Floor') + k
        src = f'''// SPDX-License-Identifier: LicenseRef-Vegan-Community-1.0
pragma solidity ^0.8.24;
// Generated by gen_floor.py from the ABI of {k}: {len(fns)} stubs{', the rest (' + str(nfwd) + ') behind fallback' if keep is not None else ''}. Size study only, never deployed.
contract {name} {{
{structs}
    address internal immutable LIB;
    bytes32 private constant _GUARD = 0xf92fce36488cd980109789c37ce44669ca2ec8fc93bcd6d944c3a5544f9ce252;
    error Reentrancy();
    constructor(address lib) {{ LIB = lib; }}
    modifier guarded() {{ bool outer = _enter(); _; _exit(outer); }}
    function _enter() private returns (bool outer) {{
        assembly ("memory-safe") {{ outer := iszero(tload(_GUARD)) }}
        if (!outer) revert Reentrancy();
        assembly ("memory-safe") {{ tstore(_GUARD, 1) }}
    }}
    function _exit(bool outer) private {{ if (outer) assembly ("memory-safe") {{ tstore(_GUARD, 0) }} }}
    function _fwd() private {{
        address l = LIB;
        assembly ("memory-safe") {{
            calldatacopy(0, 0, calldatasize())
            let ok := delegatecall(gas(), l, 0, calldatasize(), 0, 0)
            returndatacopy(0, 0, returndatasize())
            if iszero(ok) {{ revert(0, returndatasize()) }}
            return(0, returndatasize())
        }}
    }}
    function _fwdView() private view {{
        function() internal f = _fwd;
        function() internal view v;
        assembly ("memory-safe") {{ v := f }}
        v();
    }}
    function _fwdPure() private pure {{
        function() internal f = _fwd;
        function() internal pure v;
        assembly ("memory-safe") {{ v := f }}
        v();
    }}
{fb}
{chr(10).join(fns)}
}}
'''
        open(os.path.join(outdir, name + '.sol'), 'w').write(src)
        print(name, len(fns), 'stubs', nfwd, 'behind fallback' if keep is not None else '')


if __name__ == '__main__':
    main()
